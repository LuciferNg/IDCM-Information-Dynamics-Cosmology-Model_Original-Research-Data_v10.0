# cosine 展開
def cos_series(theta, terms):
    """cos(θ) Taylor 展開到 terms 項"""
    s = 0.0
    for k in range(terms):
        s += ((-1)**k) * (theta**(2*k)) / math.factorial(2*k)
    return s

