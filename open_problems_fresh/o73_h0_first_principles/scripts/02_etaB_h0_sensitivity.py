"""
O73 攻堅 02: η_B 對 H₀ 敏感度 — 「結構常數」定「H₀ fit」?
=====================================================================
η_B = Ω_b·ρ_c/(m_p·n_γ)
    ρ_c = 3H₀²/8πG     ← H₀² 依賴!
    n_γ = 2ζ(3)/π²·(k_B T_CMB/ħc)³  ← T_CMB 依賴 (但 T_CMB 係觀測, 固定)

問題: η_B = 6.062e-10 (0.62%) 係咪 H₀ 依賴?
  → 如果 η_B ∝ H₀², 用 Planck H₀=67.36 會變幾多?
  → 如果 η_B 對 H₀ 敏感, 咁「η_B 閉合」就係 H₀ 閉合嘅 re-label!
"""
import numpy as np

# 常數
G = 6.67430e-11       # m³/kg/s²
c = 299792458         # m/s
k_B = 1.380649e-23    # J/K
hbar = 1.054571817e-34  # J·s
m_p = 1.67262192369e-27  # kg
T_CMB = 2.72548       # K
Mpc_m = 3.085677581491367e22  # m
# 單位: H0 km/s/Mpc → s⁻¹: H0_km_s_Mpc × 1000 / Mpc_m

def eta_B(H0_km_s_Mpc):
    H0_s = H0_km_s_Mpc * 1000 / Mpc_m   # s⁻¹
    rho_c = 3 * H0_s**2 / (8 * np.pi * G)  # kg/m³
    n_gamma = 2 * 1.202056903159594 / np.pi**2 * (k_B * T_CMB / (hbar * c))**3  # m⁻³
    Omega_b = 0.04221  # IDCM 結構值
    return Omega_b * rho_c / (m_p * n_gamma)

print("=" * 72)
print("η_B 對 H₀ 敏感度")
print("=" * 72)
eta_72 = eta_B(72.59)
print(f"  H₀=72.59 → η_B = {eta_72:.4e}  (IDCM 目標 6.062e-10)")
for H0 in [67.36, 69.8, 70.0, 72.59, 73.04, 74.0]:
    e = eta_B(H0)
    print(f"  H₀={H0:6.2f} → η_B = {e:.4e}  dev from 6.062e-10 = {(e-6.0622e-10)/6.0622e-10*100:+.2f}%")

print()
print(f"  理論: η_B ∝ H₀² (因為 ρ_c ∝ H₀²)")
print(f"  H₀: 67.36→72.59 變化 {(72.59/67.36)**2-1:.1%}")
print(f"  → 如果 H₀=67.36 (Planck): η_B = {eta_B(67.36):.4e}")
print(f"    vs IDCM 目標 6.062e-10: 偏差 {(eta_B(67.36)-6.0622e-10)/6.0622e-10*100:+.1f}%")

print()
print("=" * 72)
print("分析")
print("=" * 72)
print("""
  η_B = Ω_b·ρ_c/(m_p·n_γ):
    Ω_b = 0.04221 (結構, 冇 H₀)
    ρ_c = 3H₀²/8πG (H₀² 依賴!)
    m_p, n_γ (T_CMB) = 物理常數

  → η_B ∝ H₀²
  → η_B = 6.062e-10 閉合「需要」H₀=72.59
  → 如果 H₀ = 67.36 (Planck): η_B 偏差 ~16% ❌

  🔴 但! Ω_b 係結構常數 (Ω_m/(1+13/2) = 0.31672/7.5 = 0.04221):
     Ω_b 冇 H₀, 但 η_B 有 H₀²
  → 「η_B 閉合」= 「H₀=72.59 閉合」嘅 re-label (部分)
  → η_B 唔係完全獨立於 H₀ 嘅結構閉合!
""")

print("=" * 72)
