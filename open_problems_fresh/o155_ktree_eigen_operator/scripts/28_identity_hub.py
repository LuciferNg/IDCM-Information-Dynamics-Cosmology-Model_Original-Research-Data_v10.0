#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""scripts/28_identity_hub.py — 88 係多重身份結節點 (hub)?
量化: 每個常數嘅身份數 (連接度), 88 係咪網內最高度數節點?
核心讀法: 一個算子, 多個 channel 投影 — 身份 = 唔同座標系嘅同一個事實.
"""
import mpmath as mp
mp.mp.dps = 60

N = 88
def g(k): return 4*mp.sin(mp.pi*k/176)**2

# 身份表: 常數 -> [(身份描述, 驗證 bool)]
ID = {}

# ---- 88: 身份最多嘅候選 hub ----
id88 = []
# 1. 定義: 雙鏈尺寸 = 2N_d
id88.append(("88 = 2N_d = 2×44 (雙鏈尺寸, 定義)", 88 == 2*44))
# 2. 譜: Σγ_odd (觀察者奇扇區和)
id88.append(("88 = Σγ_odd (odd k=1..87)", abs(sum(g(k) for k in range(1,89) if k%2==1) - 88) < mp.mpf('1e-40')))
# 3. 譜對和: 22 對 × B
id88.append(("88 = 22×B = 2L₅×4 (22 完整 Z₂ 對)", 88 == 22*4))
# 4. 平均: 44×μ²
id88.append(("88 = 44×μ² (N_d × γ₄₄, 平均=2 exactly)", 88 == 44*2))
# 5. 代數: F₁₁−1
id88.append(("88 = F₁₁−1 = 89−1 (Binet)", 88 == 89-1))
# 6. 稅: 90−2 = Σγ_even − μ²
id88.append(("88 = 90−2 = Σγ_even − μ² (世界減稅)", abs(sum(g(k) for k in range(1,89) if k%2==0) - 88 - 2) < mp.mpf('1e-40')))
# 7. 總和: 178−90 = 2F₁₁ − Σγ_even
id88.append(("88 = 178−90 (2F₁₁ − 世界)", 178-90 == 88))
# 8. 稅後: 92−4 (收稅世界 − 稅率 B)
id88.append(("88 = 92−4 (Σγ_even+μ² − B)", 92-4 == 88))
# 9. 樹: 33+55 = K_tree + home
id88.append(("88 = 33+55 = K_tree + home (樹+家, 新)", 33+55 == 88))
# 10. 對稱: 42+46 = (N_d−μ²)+(N_d+μ²)
id88.append(("88 = 42+46 = (N_d−2)+(N_d+2) (±μ² 圍住 N_d)", 42+46 == 88))
# 11. 自對: 44+44 = N_d+N_d
id88.append(("88 = 44+44 (N_d 自對)", 44+44 == 88))
# 12. 半鏈: 176/2
id88.append(("88 = 176/2 (半 Laplacian)", 176//2 == 88))
ID[88] = id88

# ---- 90 ----
ID[90] = [
    ("90 = Σγ_even (even k=2..88)", abs(sum(g(k) for k in range(1,89) if k%2==0) - 90) < mp.mpf('1e-40')),
    ("90 = 21×B + μ² + B (21=F₈)", 21*4+2+4 == 90),
    ("90 = F₁₁+1 = 89+1", 89+1 == 90),
    ("90 = 66+24 = 2K_tree + 2N_gen·B (O145)", 66+24 == 90),
    ("90 = 88+2 = Σγ_odd + μ²", 88+2 == 90),
]

# ---- 42 ----
ID[42] = [
    ("42 = N_d−2 = 44−2", 44-2 == 42),
    ("42 = 2F₈ = 2×21", 2*21 == 42),
    ("42 = 88−46 (觀察者側)", 88-46 == 42),
    ("42 = 178−134−2 (T13)", 178-134-2 == 42),
]

# ---- 44 ----
ID[44] = [
    ("44 = N_d = B×L₅ = 4×11", 4*11 == 44),
    ("44 = 88/2 (odd 或 even mode 數)", 88//2 == 44),
    ("44 = 46−2 = 42+2 (±μ² 包圍)", 46-2 == 44 and 42+2 == 44),
    ("44 = 22×2 = 2L₅×μ²", 22*2 == 44),
    ("44 = 176/4", 176//4 == 44),
]

# ---- 176 ----
ID[176] = [
    ("176 = 4N_d = 4×44", 4*44 == 176),
    ("176 = 134+42 (CY₃ 模數+觀察者, T13)", 134+42 == 176),
    ("176 = 2×88", 2*88 == 176),
    ("176 = 2F₁₁−2 = 178−2", 2*89-2 == 176),
]

# ---- 178 ----
ID[178] = [
    ("178 = Σγ(1..88) = 2F₁₁", abs(sum(g(k) for k in range(1,89)) - 178) < mp.mpf('1e-40')),
    ("178 = 172+2+4 (43 對+μ²+B)", 43*4+2+4 == 178),
    ("178 = 134+44 (T13)", 134+44 == 178),
    ("178 = 88+90 (觀察者+世界)", 88+90 == 178),
]

# 驗證 + 排名
print("身份表 (全部必須 ✔):")
degrees = []
for c in sorted(ID, reverse=True):
    ok = all(v for _, v in ID[c])
    degrees.append((len(ID[c]), c))
    print("\n[%3d] 身份數 = %d  %s" % (c, len(ID[c]), "✔ 全 PASS" if ok else "✘ FAIL"))
    for desc, v in ID[c]:
        print("   %s  %s" % (desc, "✔" if v else "✘"))

print("\n" + "="*62)
print("連接度排名:")
for deg, c in sorted(degrees, reverse=True):
    print("   %3d : %d 身份" % (c, deg))
print()
print("判決: 88 係網內最高度數節點 (12 身份 vs 90:5, 42:4, 44:5, 176:4, 178:4)")
print("讀法: 一個算子 (88-site 雙鏈), 多個 channel 投影:")
print("   譜座標: Σγ_odd = 22×B   計數座標: 2N_d = 44×μ²")
print("   代數座標: F₁₁−1         稅座標: 90−2")
print("   樹座標: K_tree+home     對稱座標: 42+46 = N_d±μ²")
print("身份唔係對稱星形 — 係階梯: 定義 (2N_d) → 譜 (22×B) → 投影 (其餘)")
print("="*62)
