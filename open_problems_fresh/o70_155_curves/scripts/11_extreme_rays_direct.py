"""
O70 — 11: Kähler Cone Extreme Rays (direct approach)
======================================================
直接方法: 用 M = intersection matrix between curve_basis and divisor_basis
  M_ij = C_i · D_j = volume of curve C_i at t = e_j

If M can be found, the Kähler cone extreme rays are columns of M^{-1}.
"""

import sys, os, math
import json
import numpy as np

BASE = os.path.join(os.path.dirname(__file__), "..", "..", "..")
O53 = os.path.join(BASE, "open_problems_fresh", "o53_cy3_reality", "data", "polytopes")
phi = (1 + math.sqrt(5)) / 2

print("=" * 72)
print("O70 11: Kähler Cone Extreme Rays (直接)")
print("=" * 72)

passed = 0
failed = 0
def check(name, cond, detail=""):
    global passed, failed
    if cond:
        passed += 1
        print(f"  ✅ {name} {detail}")
    else:
        failed += 1
        print(f"  ❌ {name} {detail}")

# ============ 1. Load ============
print("\n[1] Load data")
import cytools
from cytools import Polytope
from cytools.config import enable_experimental_features
enable_experimental_features()

d = json.load(open(os.path.join(O53, "cy36_98_sage_export.json")))
pts = np.array(d["points"])
p = Polytope(pts)
tri = p.triangulate()
cy = tri.get_cy()
basis = cy.divisor_basis()
cb = cy.curve_basis()
basis_0 = np.array([b-1 for b in basis])
print(f"  Divisor basis: {len(basis)}")
print(f"  Curve basis: {len(cb)}")

# ============ 2. Compute M = curve_basis × divisor_basis intersection ============
print("\n[2] Compute M_ij = C_i · D_j")
# For each curve_basis curve C_k, measure its volume at t = e_j (j-th divisor basis direction)
# The volume of curve C_k at t is: V_k(t) = Σ_j (C_k · D_j) · t_j = M_kj · t_j
# So M_kj = V_k(t = e_j)

# First, I need to find which of the 185 compute_curve_volumes outputs
# correspond to the 32 curve_basis curves.

# The volumes are computed for ALL curves, and the 32 curve_basis
# curves are among them. The curve_basis gives the indices of the
# Mori cone generators. The intersection matrix M is the volume
# of these generators at each basis direction.

# For each divisor basis direction e_j (j = 0..31):
#   cv = compute_curve_volumes(e_j) = [V_1(e_j), V_2(e_j), ..., V_185(e_j)]
#   The 32 curve_basis volumes are a subset of these 185.
#   The 32 × 32 matrix M_ij = V_i(e_j) for i = curve_basis curves

# But which of the 185 entries correspond to the 32 curve_basis curves?
# The curve_basis returns the indices of the curves that generate the Mori cone.
# These indices are 1-based divisor indices that correspond to specific curves.

# In a toric variety, curve C_k (for divisor k) is the curve that is
# dual to divisor k. For a simplicial toric variety, the intersection
# matrix M_ij = C_i · D_j should be the identity (up to a scale factor).

# Let's compute M by using the κ tensor:
# The volume of curve C_ij (adjacency pair) is: V_ij(t) = Σ_k κ_ijk · t_k
# For the 32 curve_basis curves, we need to find the right κ entries.

# Actually, the curve_basis gives the 32 curves that generate the Mori cone.
# Each is a specific curve that can be identified by its divisor index.
# The volume of curve C_k (generated by divisor k) is:
# V_k(t) = Σ_j (C_k · D_j) · t_j

# For a toric variety, C_k · D_j = δ_kj (if both are proper bases).
# So M should be the identity matrix.

# Let's verify: compute the volume of each curve_basis curve at t = e_j
# by extracting from compute_curve_volumes.

# First, find the 32 Q rows for the curve_basis curves
# by evaluating at each basis direction

print("  Computing M_ij...")
M = np.zeros((32, 32))
# For each divisor basis direction
for j in range(32):
    # t = e_j (unit vector in divisor basis direction j)
    t_ej = np.zeros(32)
    t_ej[j] = 1.0
    cv = cy.compute_curve_volumes(t_ej)
    # cv is 185-dim. The 32 curve_basis curves are a subset.
    # We need to identify which 32 entries of cv correspond to the basis curves.
    # For now, let's try: the first 32 entries of cv (they might be the basis curves)
    # Or: the entries with the largest absolute values at each direction
    if j == 0:
        # Find the 32 rows with largest total variation across directions
        pass
    
    # For now, try: the 32 curve_basis curves are the first 32 entries of cv
    # Actually, let's just use the full Q matrix and find the 32 most important rows
    # by looking at which rows have the most structure
    try:
        M[:, j] = cv[:32]  # First 32 entries might be the basis curves
    except:
        pass

# If M is the identity, the Kähler cone is the positive orthant
print(f"  M[:5,:5]:\n{M[:5,:5]}")
print(f"  M diagonal: {np.diag(M)}")
print(f"  M off-diagonal max: {np.max(np.abs(M - np.diag(np.diag(M)))):.4f}")

# Check if M is approximately identity
M_identity_like = np.allclose(M, np.eye(32), atol=0.1)
check("M ≈ I", M_identity_like, f"(max off-diag={np.max(np.abs(M - np.eye(32))):.4f})")

# If M is not identity, compute the extreme rays as columns of M^{-1}
if np.linalg.cond(M) < 1e10:
    M_inv = np.linalg.inv(M)
    print(f"  M cond: {np.linalg.cond(M):.2f}")
    print(f"  M^{-1}[:5,:5]:\n{M_inv[:5,:5]}")
    
    # The 32 columns of M^{-1} are the candidate extreme rays
    # Check: are they in the cone? Q @ t ≥ 0?
    # Compute Q_ij first
    t_test = phi ** (-np.arange(36))
    t32 = np.array([t_test[b-1] for b in basis])
    eps = 1e-4
    Q = np.zeros((185, 32))
    for jj in range(32):
        t_plus = t32.copy(); t_minus = t32.copy()
        t_plus[jj] += eps; t_minus[jj] -= eps
        cv_plus = np.array(cy.compute_curve_volumes(t_plus))
        cv_minus = np.array(cy.compute_curve_volumes(t_minus))
        Q[:, jj] = (cv_plus - cv_minus) / (2*eps)
    
    valid_rays = 0
    for k in range(32):
        t_k = M_inv[:, k]
        t_k = t_k / np.linalg.norm(t_k)
        vols = Q @ t_k
        if np.all(vols > -1e-6):
            valid_rays += 1
            if valid_rays <= 5:
                print(f"  Ray {k}: ✅ min vol={vols.min():.4f}")
        else:
            if k < 5:
                print(f"  Ray {k}: ❌ min vol={vols.min():.4f}")
    
    print(f"  Valid extreme rays: {valid_rays}/32")
    check("All rays in cone", valid_rays == 32, f"({valid_rays}/32)")

print(f"\nPassed: {passed}, Failed: {failed}")