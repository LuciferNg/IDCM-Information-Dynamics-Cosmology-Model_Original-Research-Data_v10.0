#!/usr/bin/env python3
"""
O70 — 18: Extreme Rays via Double Description (純 Python)
===========================================================
從 99 條 LP boundary rays 中找出 minimal generating set = extreme rays。
方法: 每個 ray 檢驗能否被其他 rays 正組合表示。
"""

import sys, os, math, json, numpy as np
from scipy.optimize import linprog
import scipy.linalg

BASE = os.path.join(os.path.dirname(__file__), "..", "..", "..")
O53 = os.path.join(BASE, "open_problems_fresh", "o53_cy3_reality", "data", "polytopes")
phi = (1 + math.sqrt(5)) / 2

print("=" * 72)
print("O70 18: Extreme Rays — Minimal Generating Set")
print("=" * 72)

# Load 99 rays
R = np.load(os.path.join(os.path.dirname(__file__), "..", "data", "15_all_rays.npy"))
print(f"Input: {len(R)} rays, rank {np.linalg.matrix_rank(R)}")

# Normalize
Rn = R / np.linalg.norm(R, axis=1, keepdims=True)

# For each ray, check if it's in the cone generated by the others
# Use LP: find λ ≥ 0 such that Σ λ_i * r_i = r
# This is: minimize ||r - Σ λ_i r_i||² s.t. λ ≥ 0
# If the residual is small, r is not extreme.

# To make it faster: use the SVD basis
# Project all rays to the 32D coordinate space
# For each r, check if r is in the positive cone of the others

extreme_indices = []
n_rays = len(Rn)

for k in range(n_rays):
    r = Rn[k]
    others = np.delete(Rn, k, axis=0)  # (n-1) × 32
    
    # Use non-negative least squares: minimize ||others^T @ λ - r||² s.t. λ ≥ 0
    # This is a convex optimization problem
    # scipy.optimize.nnls is fast for this
    
    from scipy.optimize import nnls
    sol, residual = nnls(others.T, r)
    
    if residual > 1e-6:
        # r cannot be represented as positive combination of others → extreme
        extreme_indices.append(k)
        if len(extreme_indices) <= 32 or len(extreme_indices) % 5 == 0:
            print(f"  Extreme ray {len(extreme_indices)}: index {k}, residual={residual:.2e}")

print(f"\nTotal extreme rays: {len(extreme_indices)}/{n_rays}")

if len(extreme_indices) > 0:
    R_extreme = Rn[extreme_indices]
    rank_ext = np.linalg.matrix_rank(R_extreme)
    print(f"Extreme rank: {rank_ext}/{len(extreme_indices)}")
    
    # Save
    out_path = os.path.join(os.path.dirname(__file__), "..", "data", "18_extreme_rays.npy")
    np.save(out_path, R_extreme)
    print(f"Saved to {out_path}")
    
    if rank_ext == 32:
        print("✅ Full 32D cone spanned by extreme rays!")
    elif rank_ext == 32 and len(extreme_indices) >= 32:
        print(f"🟡 {len(extreme_indices)} extreme rays, rank {rank_ext}/32")
    else:
        print(f"⚠️ Only rank {rank_ext}/32, need more rays")

print("Done.")