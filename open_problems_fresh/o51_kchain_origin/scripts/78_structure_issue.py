#!/usr/bin/env python3
"""
O51/78: D_app 公式結構根源推導 — 找出原始公式嘅遺漏項
===============================================================
唔係 fit DESI，而係比較原始公式同 K_Chain 譜嘅「加權投影」

原始公式推導:
  D_app(ℓ) = (44 − 44/4^ℓ)(R_H/44)(1 + 2φ⁻¹ℓ)
  
假設: 所有 44 個模式嘅投影權重相同 (uniform)

結構問題: K_Chain 譜 γ_n 從 0.005 到 4，分布不均勻
  模式 n 嘅「投影能量」= γ_n，唔係 1
  
重新推導: 用 Σγ 加權投影
"""
import json, math

PASS = 0
FAIL = 0
def check(name, cond, detail=""):
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  ✅ PASS: {name}")
    else:
        FAIL += 1
        print(f"  ❌ FAIL: {name}")
    if detail:
        print(f"    {detail}")

R_H = 4129.94
N_d = 44
phi = (1 + math.sqrt(5)) / 2

print("=" * 62)
print("D_app 公式結構根源 — 加權投影 vs 均勻投影")
print("=" * 62)

# ============ 1. K_Chain 譜 ============
gamma = [4*math.sin(math.pi*n/88)**2 for n in range(1, N_d+1)]
sum_gamma = sum(gamma)

# 均勻投影: 每個模式權重 = 1
# 加權投影: 每個模式權重 = γ_n
# 歸一化: 權重和 = 44 (均勻) 或 90 (加權)

# ============ 2. D_app 原始公式拆解 ============
# 原始公式: D_app = A(ℓ) × B × C(ℓ)
# A(ℓ) = (44 − 44/4^ℓ) — 模式存活數
# B = R_H/44 — 格點間距
# C(ℓ) = (1 + 2φ⁻¹ℓ) — 投影伸長

# 但係 K_Chain 譜嘅「模式存活數」應該用能量加權：
# S_weighted(ℓ) = Σγ_n × (1 − 4^{−ℓ})  — 所有模式相同粗粒化速率
# = 90 × (1 − 4^{−ℓ})

# 原始公式用 S_uniform(ℓ) = 44 × (1 − 4^{−ℓ})
# 差別: (90 − 44) × (1 − 4^{−ℓ}) = 46 × (1 − 4^{−ℓ})

print("\n--- 原始公式拆解 ---")
print(f"Σγ = {sum_gamma:.1f}")
print(f"N_d = {N_d}")
print(f"ratio = Σγ/N_d = {sum_gamma/N_d:.4f}")

# 呢個 ratio 等於 90/44 = 2.04545...
# 2.04545... 有冇結構意義?
# 2 = F₃ (Fibonacci), 45 = ?
# 45 = 90/2 = Σγ/2 = (44+46)/2
# 或者 45 = N_d + 1 = 44+1
# 或者 45 = B² + L₄ + 1 = 16+7+22? 唔係

# 90/44 = 2.04545... = (Σγ_even + Σγ_odd)/N_d = (46+44)/44 = 90/44
# 冇簡化結構

# ============ 3. 關鍵結構問題 ============
print("\n--- 關鍵結構問題: 均勻 vs 加權投影 ---")

# 原始公式假設: 所有 44 個模式投影到天球嘅「權重」相同
# 但係 K_Chain 譜 γ_n 唔同: n=1 時 γ=0.005, n=44 時 γ=4
# 高頻模式 (n大) 嘅投影能量大過低頻模式 (n小) 800 倍!

# 正確嘅「模式存活數」應該係:
# S(ℓ) = Σγ_n × 4^{−ℓ}  (保留模式嘅能量)  
# 而唔係 44 × 4^{−ℓ} (保留模式嘅數量)

# 原始公式用整數計數 44 代替能量和 90
# 偏差 = 90/44 − 1 = 104.5% — 但呢個係 ℓ=0 時嘅偏差
# 隨 ℓ 增加, 偏差改變

# 真正嘅結構問題: 高頻模式 (n大, γ_n大) 先被粗粒化
# 所以模式存活唔係 uniform 4^{−ℓ}，而係「先死大嘅, 留低細嘅」

print("高頻模式 (n=44, γ=4.0) 先被粗粒化")
print("低頻模式 (n=1, γ=0.005) 後被粗粒化")
print("-> 有效模式數隨 ell 嘅衰減唔係簡單 4^{-ell}")

# ============ 4. 階梯式粗粒化模型 ============
print("\n--- 階梯式粗粒化 (K_Tree 33 層) ---")

# K_Tree 有 33 層, 每層粗粒化 B=4 倍
# 層 ℓ 對應嘅「模式截止」: n_cut(ℓ) = 44 × 4^{−ℓ} (近似)
# 即係 ℓ=0 時有 44 個模式, ℓ=1 時有 11 個模式, ℓ=2 時有 2.75 個模式...

# 但係模式係離散嘅, 所以「截止」係階梯式, 唔係連續
# ℓ=0: n=1..44 (44 個模式)
# ℓ=1: n=1..11 (11 個模式)
# ℓ=2: n=1..2 (2 個模式)
# ℓ=3: n=1 (1 個模式)

# 而家計算「存活模式數」同「存活能量和」嘅關係:
for ell in range(0, 5):
    n_cut = max(1, int(44 / 4**ell))
    survivors = gamma[:n_cut]
    n_surv = len(survivors)
    e_surv = sum(survivors)
    print(f"ℓ={ell}: n_cut={n_cut}, 存活模式={n_surv}, 存活能量={e_surv:.1f}, 能量/模式={e_surv/n_surv:.2f}")

# 關鍵發現: 存活能量/存活模式 隨 ℓ 增加而減少!
# 因為高能量模式 (n大) 先被 cut

# ============ 5. D_app 加權投影公式 ============
print("\n--- 加權投影公式推導 ---")

# 原始公式 D_app(ℓ) = (44 − 44/4^ℓ)(R_H/44)(1 + 2φ⁻¹ℓ)
# 加權版本: 用 Σγ 代替 44, 用 R_H/Σγ 代替 R_H/44
# 但係物理上 R_H/44 係 K_Chain 格點間距, 冇得改

# 真正嘅問題係: (44 − 44/4^ℓ) 應該係 (N_eff(ℓ) − N_eff(ℓ→∞))
# 其中 N_eff(ℓ) = 第 ℓ 層嘅「有效投影模式數」

# 有效投影模式數 = Σγ_n × 4^{−ℓ} (能量加權)
# 但係原始公式用 = 44 × 4^{−ℓ} (數量加權)

# 偏差項 = Σγ_n × 4^{−ℓ} − 44 × 4^{−ℓ} = 46 × 4^{−ℓ}
# 呢個偏差隨 ℓ 增加而衰減

# 积分到 D_app:
# ΔD_app(ℓ) = (R_H/44) × ∫₀^ℓ 46 × 4^{−ℓ'} × (1 + 2φ⁻¹ℓ') dℓ'
# = (R_H/44) × 46 × [∫₀^ℓ 4^{−ℓ'} dℓ' + 2φ⁻¹∫₀^ℓ ℓ'4^{−ℓ'} dℓ']

# 第一項: ∫₀^ℓ 4^{−ℓ'} dℓ' = (1 − 4^{−ℓ})/ln4
# 第二項: ∫₀^ℓ ℓ'4^{−ℓ'} dℓ' = [1 − (1 + ℓ ln4)4^{−ℓ}]/ln4²

# 所以 ΔD_app(ℓ) = (R_H/44) × 46 × [(1 − 4^{−ℓ})/ln4 + 2φ⁻¹(1 − (1 + ℓ ln4)4^{−ℓ})/ln4²]

# 原始公式: D_app_0(ℓ) = (R_H/44) × 44 × (1 − 4^{−ℓ})(1 + 2φ⁻¹ℓ)
# 加權修正: D_app(ℓ) = D_app_0(ℓ) + ΔD_app(ℓ)

print(f"原始公式: D_0(ell) = (R_H/44) x 44 x (1-4^{-ell})(1 + 2*phi^{-1}*ell)")
print(f"能量偏差: Delta(ell) = Sigma_gamma - 44 = 46 (constant)")
print(f"加权修正: D(ell) = D_0(ell) + Delta D_app(ell)")

# ============ 6. 驗證 ============
def D_original(ell):
    return (44 - 44/4**ell) * (R_H/44) * (1 + 2*phi**(-1)*ell)

def D_weighted(ell):
    """加權投影: 用 Σγ=90 代替 44"""
    ln4 = math.log(4)
    term1 = (1 - 4**(-ell)) / ln4
    term2 = (1 - (1 + ell*ln4)*4**(-ell)) / (ln4**2)
    delta = (R_H/44) * 46 * (term1 + 2*phi**(-1) * term2)
    return D_original(ell) + delta

# 測試
zs = [0.295, 0.510, 0.706, 0.934, 1.321, 1.484, 2.330]
print(f"\n{'z':<6} {'ℓ':<6} {'D_orig':<10} {'D_weight':<10} {'ratio':<8}")
print("-" * 30)
for z in zs:
    ell = math.log(1+z, 4)
    D1 = D_original(ell)
    D2 = D_weighted(ell)
    print(f"{z:<6.3f} {ell:<6.3f} {D1:<10.2f} {D2:<10.2f} {D2/D1:<8.4f}")

# ============ 7. 結構問題總結 ============
print(f"\n{'=' * 62}")
print("結構問題總結")
print("=" * 62)
print(f"""
1. 原始公式用模式數 (44) 代替模式能量 (Σγ=90)
   → 忽略咗高頻模式 (n=44, γ=4.0) vs 低頻模式 (n=1, γ=0.005) 嘅投影權重差異

2. 粗粒化係「先大後細」— 高能量模式先被粗粒化
   -> 有效模式數隨 ell 嘅衰減唔係簡單 4^{-ell}

3. 間隙: 44 (計數) vs 90 (能量) = 46
   46 = Σγ_even (偶數模式能量和)
   → 偶數模式 (n=2,4,...,44) 嘅能量總和 = 46

4. 階梯修正: 46 係「偶數模式超額能量」
   → 低 ℓ 時, 偶數模式主導投影 (因為佢哋能量高)
   → 高 ℓ 時, 奇數模式主導 (因為佢哋能量低, 留得耐)
""")

check("加權投影 ≠ 均勻投影 (結構問題)", D_weighted(0.3) != D_original(0.3))

result = {
    'sum_gamma': sum_gamma,
    'N_d': N_d,
    'gamma_ratio': sum_gamma/N_d,
    'excess': sum_gamma - N_d,
    'pass': PASS, 
    'fail': FAIL
}

with open('data/78_structure_issue.json', 'w') as f:
    json.dump(result, f, indent=2, default=str)

print(f"\n✅ 結果 -> data/78_structure_issue.json")