#!/usr/bin/env python3
"""
O10 70: 質數峰相位 — ±1, ±23 (mod 88) 鎖定
============================================
ℓ mod 88: 45, 87, 23, 65, 1
  45 = 44+1
  87 = 88-1
  23
  65 = 88-23
  1

→ 質數峰 ℓ ≡ ±1, ±23 (mod 88)
  或者: ℓ mod 44 = 1, 43, 23, 21, 1
  = ±1, ±21 (mod 44)?

檢查:
  221 mod 44 = 1 ✓
  527 mod 44 = 43 = -1 ✓
  815 mod 44 = 23
  1121 mod 44 = 21 = -23 ✓
  1409 mod 44 = 1 ✓

→ ℓ mod 44 ∈ {1, 21, 23, 43} = {±1, ±21}
  而 21 = -23 mod 44? 23+21 = 44 ✓!
"""
import numpy as np, math

print("=" * 72)
print("質數峰相位 ±1, ±23 (mod 88)")
print("=" * 72)

ells = {1: 221, 2: 527, 3: 815, 5: 1121, 7: 1409}
N = {1: 5, 2: 12, 3: 18, 5: 25, 7: 32}

print(f"{'m':>2} | {'ℓ':>5} | {'mod 88':>6} | {'mod 44':>6} | 相位")
print("-" * 45)
for m in [1, 2, 3, 5, 7]:
    mod88 = ells[m] % 88
    mod44 = ells[m] % 44
    print(f"{m:>2} | {ells[m]:>5} | {mod88:>6} | {mod44:>6} | {ells[m]} = 44×{N[m]}+{ells[m]-44*N[m]}")

print()
print("mod 88: 45, 87, 23, 65, 1")
print("  45 = 44+1 (即 +1 mod 44)")
print("  87 = 88-1 (即 -1 mod 44)")
print("  23")
print("  65 = 88-23 (即 -23 mod 44)")
print("  1")
print()
print("→ 質數峰 ℓ mod 88 ∈ {1, 23, 45, 65, 87} = {±1, ±23} ∪ {45}")
print("  45 = 44+1, 所以 mod 44 = 1")
print()
print("精確: ℓ mod 44 ∈ {1, 21, 23, 43}")
print("  1, 21, 23, 43 = ±1, ±21")
print("  21 = 23-2? 定係 -23 mod 44? 21+23 = 44 ✓")
print()
print("🎯 質數峰 ℓ ≡ ±1, ±21 (mod 44)")
print("  即 ℓ = 44N ± 1 或 44N ± 21")
print()

# 驗證所有質數峰
print("驗證: ℓ = 44N + s, s ∈ {±1, ±21}:")
ok = True
for m in [1, 2, 3, 5, 7]:
    l = ells[m]
    s = l - 44*N[m]
    valid = s in (1, -1, 21, -21, 23)  # 23 = 44-21
    ok &= (s % 44) in (1, 43, 21, 23)
    print(f"  m={m}: ℓ={l}, N={N[m]}, s={s:+d}, s mod 44 = {s%44} {'✅' if s%44 in (1,43,21,23) else '❌'}")
print(f"全部通過: {'✅' if ok else '❌'}")
print()

# 相位結構意義
print("=" * 72)
print("相位結構意義")
print("=" * 72)
print("K_Chain: 44 sites, 峰位 = 44N + s")
print("s ∈ {±1, ±21}: 峰位喺格點 ±1 (近格點) 或 ±21 (近半格點)")
print()
print("21 = 44/2 - 1 = 22-1 → 半格點 -1")
print("所以相位 = {±1, 22±1}: 格點±1 同半格點±1")
print()
print("即: 質數峰喺格點或半格點嘅 ±1 位置")
print("  44N±1: 格點附近")
print("  44N±21: 半格點附近 (21=22-1)")
print()
print("呢個同「質數」有咩關係?")
print("  質數 p 對應 s = (-1)^(j-1) (之前發現)")
print("  m1: +1, m2: -1, m3: +1(mod22)=23, m5: -1(mod22)=21, m7: +1")
print()
print("s mod 22 = ±1 交替:")
print("  m1: 1, m2: 21, m3: 1, m5: 21, m7: 1")
print("  → 奇數質數階 (m1, m3, m7): +1")
print("  → 偶數質數階 (m2, m5): -1")
print()
print("但 m5 (質數 5) 係第 4 個質數 (1,2,3,5) — 偶數階 → -1 ✓")
print("m3 (質數 3) 係第 3 個 — 奇數階 → +1 ✓")
