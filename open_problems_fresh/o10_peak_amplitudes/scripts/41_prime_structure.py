#!/usr/bin/env python3
"""
O10 41: 質數峰高度結構 — 最終公式
==================================
真峰 m ∈ {1,2,3,5,7} (質數+1)
高度:
  A(m1) = 1.0000
  A(m2) = 0.4434
  A(m3) = 0.4389
  A(m5) = 0.2143
  A(m7) = 0.1414

結構假設: A(m_p) = 3ε·F_{p-1}·φ^(-a_p)?
  或者質數峰高度有另一結構?
"""
import numpy as np, math

phi = (1 + 5**0.5) / 2
eps = phi**-1/4
F = [1, 1, 2, 3, 5, 8, 13, 21, 34]

A = {1: 1.0000, 2: 0.4434, 3: 0.4389, 5: 0.2143, 7: 0.1414}
ell = {1: 221, 2: 527, 3: 815, 5: 1121, 7: 1409}

print("=" * 72)
print("質數峰高度結構")
print("=" * 72)

# 睇 log 結構
print("ln(A):")
for m in [1, 2, 3, 5, 7]:
    print(f"  m={m}: ln(A) = {math.log(A[m]):.4f}")

print()
print("ln(A) vs ln(ℓ):")
for m in [2, 3, 5, 7]:
    slope = math.log(A[m])/math.log(ell[m]/ell[1])
    print(f"  m={m}: slope = {slope:.3f}")

print()
print("如果 A ∝ ℓ^(-α):")
# 用 m2, m7
alpha = math.log(A[2]/A[7])/math.log(ell[7]/ell[2])
print(f"  α = ln(A2/A7)/ln(ℓ7/ℓ2) = {alpha:.3f}")

print()
print("如果 A(m) = 3ε·φ^(-β(m)):")
for m in [2, 3, 5, 7]:
    beta = -math.log(A[m]/(3*eps))/math.log(phi)
    print(f"  m={m}: β = {beta:.4f}")

print()
print("β: 0.092, 0.113, 1.603, 2.467")
print("β(m2)≈β(m3)≈0.1, β(m5)≈1.6, β(m7)≈2.47")
print("β(m5) ≈ φ = 1.618? 偏差", (1.603-phi)/phi*100)
print("β(m7) ≈ 2.47 ≈ φ²-0.15?")
print()

# 試: 質數峰 β = (p-1)/2 × φ? 
# m=2 (p=2): β=0.1 ≈ 0?
# m=3 (p=3): β=0.1 ≈ 0?
# m=5 (p=5): β=1.6 ≈ φ⁻¹+1? = 1.618
# m=7 (p=7): β=2.47 ≈ φ? ×1.5 = 2.427? 接近!
print("β(m5) ≈ φ, β(m7) ≈ φ×1.5 =", phi*1.5)
print("β(m2)≈β(m3)≈0 → 前三個峰 φ⁰ 級")
print()

# 更重要: 質數峰 = Fibonacci 階梯嘅「奇數項」?
# F_m 階梯: m=1(F₁=1), m=2(F₂=1), m=3(F₃=2), m=5(F₅=5), m=7(F₇=13)
# 峰高度 vs F_m?
print("峰高 vs F_m (m = 質數):")
for m in [2, 3, 5, 7]:
    print(f"  m={m}: F_{m} = {F[m-1]}, A = {A[m]:.4f}, A×F_{m} = {A[m]*F[m-1]:.4f}")

print()
print("A×F_m: 0.4434, 0.8778, 1.0715, 1.8382")
print("有趣: A(m3)×F₃ = 0.878 ≈ 2×0.439")
print("       A(m7)×F₇ = 1.838 ≈ 2×0.919")
print()

# 但 P_m 公式: P_m = 3ε·F_m·φ^(-2(m-1))
# 峰 m 嘅「P 值」如果 m 係質數:
# P(m2) = 3ε·F₂·φ⁰ = 3ε = 0.4635 vs 0.4434 (-4.3%)
# P(m3) = 3ε·F₃·φ⁻² = 0.1771 vs 0.4389? 唔啱!
print("質數峰唔直接 fit P_m 公式 (m2, m3 唔同 P 值)")
print()
print("結論: 質數峰結構需要更深層理論")
print("  1. 真峰 m ∈ {1,2,3,5,7} = 質數 (合數峰消失)")
print("  2. A(m2)≈A(m3)≈3ε (前兩個峰)")
print("  3. A(m5), A(m7) 遞減 (β≈φ, 1.5φ)")
print()
print("呢個可能係「質數調和」或者「K_Chain 質數模式」結構")
print("→ 需要獨立 O 系列跟進 (O41?)")
