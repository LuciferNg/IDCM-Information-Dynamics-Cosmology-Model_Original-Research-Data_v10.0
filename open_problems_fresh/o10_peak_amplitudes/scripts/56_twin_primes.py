for m in [1, 2, 3, 5, 7]:
    print(f"  m={m}: N = {N[m]}, ℓ = {ell[m]}")

print()
print("N_m 分解:")
decomp = {
    5: [(2, 3), (1, 4)],
    12: [(5, 7), (3, 9), (1, 11)],
    18: [(7, 11), (5, 13), (3, 15)],
    25: [(12, 13), (2, 23), (11, 14)],
    32: [(13, 19), (3, 29), (7, 25)],
}
for m in [1, 2, 3, 5, 7]:
    print(f"  N={N[m]} (m={m}): 質數對候選: {decomp[N[m]]}")

print()
print("觀察:")
print("  5 = 2+3 (孿生質數, 差1)")
print("  12 = 5+7 (孿生質數, 差2)")
print("  18 = 7+11 (差4)")
print("  32 = 13+19 (差6)")
print()
print("質數對差: 1, 2, 4, 6 — 偶數遞增!")
print("或者: 質數對 = (p, p+g) g = 1, 2, 4, 6?")
print()
print("但 25 = 12+13? 12 唔係質數")
print("  25 = 2+23 ✓ (23 質數) 但差 21 好大")
print("  或者 25 = 11+14? 唔係")
print()

# 另一角度: N_m 本身嘅結構
print("N_m: 5, 12, 18, 25, 32")
