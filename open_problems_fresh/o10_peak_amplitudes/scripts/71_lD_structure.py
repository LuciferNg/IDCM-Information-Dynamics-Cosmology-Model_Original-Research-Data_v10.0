print()

candidates = {
    "N×M×F₅": N*M*5,
    "N×M×F₄": N*M*3,
    "M²×φ²": M**2*phi**2,
    "N²×φ²": N**2*phi**2,
    "N×S×φ": N*S*phi,
    "M×S×φ": M*S*phi,
    "N×M×φ²": N*M*phi**2,
    "S²×φ": S**2*phi,
    "S×M×3": S*M*3,
    "S×M×3.05": S*M*3.05,
    "N×M×6.24": N*M*6.24,
    "N×N×φ×3": N*N*phi*3,
    "M×F₉×8": M*34*8,
    "M×F₉×φ²": M*34*phi**2,
    "N×F₉×6": N*34*6,
    "88×103": 88*103,
    "88×102.9": 88*102.9,
    "90×100.6": 90*100.6,
    "88×88×1.17": 88*88*1.17,
    "44×206": 44*206,
    "44×205.8": 44*205.8,
    "90×100": 90*100,
    "88×100+255": 88*100+255,
    "44×F₉×F₉": 44*34*34,
    "M×M×8.3": 33*33*8.3,
}

for name, val in candidates.items():
    dev = (val-lD)/lD*100
    if abs(dev) < 5:
        print(f"  {name} = {val:.1f} (偏差 {dev:+.2f}%)")

