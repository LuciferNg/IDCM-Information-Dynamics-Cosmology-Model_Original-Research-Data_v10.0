#!/usr/bin/env python3
"""
O10 39: 峰 m 重數 = F_{m-1} 完整驗證
=====================================
假設: 每峰獨立重數
  峰 2 = F₁ = 1
  峰 3 = F₂ = 1  → 比 1:1 ✅ (0.99)
  峰 4 = F₃ = 2
  峰 5 = F₄ = 3  → 比 2:3 = 0.667 ✅ (0.66)

但峰高公式? 峰 4,5 共享 P₂ = 3εφ⁻², 按 F₃:F₄ = 2:3 分配
  峰 4 = P₂×2/5, 峰 5 = P₂×3/5
"""
import numpy as np, math

phi = (1 + 5**0.5) / 2
eps = phi**-1/4
F = [1, 1, 2, 3, 5, 8, 13, 21, 34]

# Planck 真峰
A = {1: 1.0000, 2: 0.4434, 3: 0.4389, 4: 0.2143, 5: 0.1414}

print("=" * 72)
print("峰 m 重數 = F_{m-1} 驗證")
print("=" * 72)
print(f"{'峰':>2} | {'F_{m-1}':>6} | {'A_obs':>7} | {'A_pred':>7} | {'偏差':>7}")
print("-" * 45)

# 峰 2,3: 共享 P₁ = 3ε, 按 F₁:F₂ = 1:1
P1 = 3*eps
A2_pred = P1 * F[0]/(F[0]+F[1])
A3_pred = P1 * F[1]/(F[0]+F[1])
print(f"{2:>2} | {F[0]:>6} | {A[2]:>7.4f} | {A2_pred:>7.4f} | {(A[2]-A2_pred)/A2_pred*100:>+6.2f}%")
print(f"{3:>2} | {F[1]:>6} | {A[3]:>7.4f} | {A3_pred:>7.4f} | {(A[3]-A3_pred)/A3_pred*100:>+6.2f}%")

# 峰 4,5: 共享 P₂ = 3εφ⁻², 按 F₃:F₄ = 2:3
P2 = 3*eps*phi**-2
A4_pred = P2 * F[2]/(F[2]+F[3])
A5_pred = P2 * F[3]/(F[2]+F[3])
print(f"{4:>2} | {F[2]:>6} | {A[4]:>7.4f} | {A4_pred:>7.4f} | {(A[4]-A4_pred)/A4_pred*100:>+6.2f}%")
print(f"{5:>2} | {F[3]:>6} | {A[5]:>7.4f} | {A5_pred:>7.4f} | {(A[5]-A5_pred)/A5_pred*100:>+6.2f}%")

print()
print("但 A4_pred = 0.0708 vs obs 0.2143 — 差 3 倍!")
print("問題: 峰 4,5 唔係共享 P₂, 而係各自有 P_m?")
print()

# 重新理解: 峰 4,5 各自 = 3ε·(自己重數)·φ^(-2(m-1))?
# 峰 4 = 3ε·F₃·φ^(-2?)...
# 或者峰 4,5 唔屬於同一個 P_m?
print("另一詮釋: 峰 4 同峰 5 係唔同「代」?")
print("  峰 4 (ℓ=1121) = IDCM m=5 (O9 修正)")
print("  峰 5 (ℓ=1409) = IDCM m=7 (1400)")
print()

# O9 峰位: 221(1), 527(2), 815(3), 1013(4), 1121(5), 1337(6), 1400(7)
# 真峰: 221, 527, 815, 1121, 1409
# → 真峰 4 = IDCM m5, 真峰 5 ≈ IDCM m7
# 所以「簡併對」(4,5) 其實係 IDCM m5 + m7 嘅組合!
print("真峰 4 (1121) = IDCM m=5, 真峰 5 (1409) ≈ IDCM m=7")
print("→ 唔係簡併對, 係隔代組合!")
print()
print("IDCM 峰位: 221(m1), 527(m2), 815(m3), 1013(m4), 1121(m5), 1337(m6), 1400(m7)")
print("Planck 真峰: 221, 527, 815, 1121, 1409")
print("對應: m1, m2, m3, m5, m7")
print()
print("峰高 (Planck):")
for m, le, A_ in [(1, 221, 1.0), (2, 527, 0.4434), (3, 815, 0.4389), (5, 1121, 0.2143), (7, 1409, 0.1414)]:
    print(f"  IDCM m{m} @ {le}: A = {A_:.4f}")
print()
print("注意: m4 (1013) 同 m6 (1337) 唔係真峰!")
print("→ 峰高公式應該直接對 IDCM m 編號:")
print("  A(m1) = 1")
