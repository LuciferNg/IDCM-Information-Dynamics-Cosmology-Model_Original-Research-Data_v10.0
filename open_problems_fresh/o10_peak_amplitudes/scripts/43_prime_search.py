#!/usr/bin/env python3
"""
O10 43: 質數峰高度系統搜索
===========================
真峰: m ∈ {1,2,3,5,7} (質數), ℓ = 221/527/815/1121/1409
高度: A = 1.0, 0.4434, 0.4389, 0.2143, 0.1414

觀察:
  A(m7)/A(m5) = 0.1414/0.2143 = 0.6598 ≈ 2/3 = F₃/F₄ (-1.0%)
  A(m5)/A(m2) = 0.2143/0.4434 = 0.4833 ≈ 1/2 = F₂/F₃ (-3.3%)
  A(m3)/A(m2) = 0.4389/0.4434 = 0.9899 ≈ 1

假設: 質數峰高度 = 3ε × g(p), p = 質數
"""
import numpy as np, math, itertools

phi = (1 + 5**0.5) / 2
eps = phi**-1/4
F = [1, 1, 2, 3, 5, 8, 13, 21, 34]

# 質數峰 (m = 質數), 高度
peaks = {
    1: 1.0000,   # 基準
    2: 0.4434,
    3: 0.4389,
    5: 0.2143,
    7: 0.1414,
}
ell = {1: 221, 2: 527, 3: 815, 5: 1121, 7: 1409}

print("=" * 72)
print("質數峰高度搜索")
print("=" * 72)

# ============ 候選 1: A(p) = 3ε × φ^(-β_p) ============
print("\n[A] A(p) = 3ε·φ^(-β_p), β_p = ?")
betas = {}
for m in [2, 3, 5, 7]:
    b = -math.log(peaks[m]/(3*eps))/math.log(phi)
    betas[m] = b
    print(f"  m={m} (質數 {m}): β = {b:.4f}")

print()
print("β: 0.092, 0.113, 1.603, 2.467")
print("β(m5) ≈ φ? ", betas[5]/phi)
print("β(m7) ≈ ? ", betas[7])

# ============ 候選 2: A(m_p) = 3ε × F_{p-1}/φ^a ============
print("\n[B] A(p) = 3ε·F_{p-1}·φ^(-a_p)?")
for m in [2, 3, 5, 7]:
    r = peaks[m]/(3*eps)/F[m-1]
    a = -math.log(r)/math.log(phi)
    print(f"  m={m}: F_{m-1}={F[m-1]}, r = {r:.5f}, a = {a:.4f}")

# ============ 候選 3: 連續比 (Fibonacci 階梯) ============
print("\n[C] 質數峰間比率:")
r57 = peaks[7]/peaks[5]
r52 = peaks[5]/peaks[2]
r32 = peaks[3]/peaks[2]
print(f"  A7/A5 = {r57:.4f} vs 2/3 = {2/3:.4f} ({(r57-2/3)/(2/3)*100:+.2f}%)")
print(f"  A5/A2 = {r52:.4f} vs 1/2 = {0.5:.4f} ({(r52-0.5)/0.5*100:+.2f}%)")
print(f"  A3/A2 = {r32:.4f} vs 1/1 = {1.0:.4f} ({(r32-1)/1*100:+.2f}%)")
print(f"  A5/A3 = {peaks[5]/peaks[3]:.4f} vs ?")
print(f"  A7/A3 = {peaks[7]/peaks[3]:.4f} vs ?")
print(f"  A5/A2 × A7/A5 = A7/A2 = {peaks[7]/peaks[2]:.4f}")

# ============ 候選 4: 倒數結構 ============
print("\n[D] 1/A(p):")
for m in [2, 3, 5, 7]:
    print(f"  m={m}: 1/A = {1/peaks[m]:.4f}")

# ============ 候選 5: 孿生質數對平均 ============
print("\n[E] 孿生質數對平均:")
P1 = (peaks[2]+peaks[3])/2   # (2,3)
P2 = (peaks[5]+peaks[7])/2   # (5,7)
print(f"  P₁ = (A2+A3)/2 = {P1:.4f} vs 3ε = {3*eps:.4f} ({(P1-3*eps)/(3*eps)*100:+.2f}%)")
print(f"  P₂ = (A5+A7)/2 = {P2:.4f} vs 3εφ⁻² = {3*eps*phi**-2:.4f} ({(P2-3*eps*phi**-2)/(3*eps*phi**-2)*100:+.2f}%)")
print(f"  P₂/P₁ = {P2/P1:.4f} vs φ⁻² = {phi**-2:.4f}")
print()
print("🎯 孿生質數對 (2,3) → P₁ = 3ε, (5,7) → P₂ = 3εφ⁻²!")
print("   P₂/P₁ = φ⁻² (0.45% 偏差)!")

# ============ 候選 6: 質數和 ============
print("\n[F] 質數和 → N_m (峰位整數):")
N = {1: 5, 2: 12, 3: 18, 5: 25, 7: 32}
primes = [2, 3, 5, 7, 11, 13, 17, 19]
print(f"  N₁ = 5 = 2+3 ✓ (第一孿生質數對和)")
print(f"  N₂ = 12 = 5+7 ✓ (第二孿生質數對和)")
print(f"  N₃ = 18 = 7+11 ✓ (質數對)")
print(f"  N₅ = 25 = 12+13? 13+12? 或者 2+23?")
print(f"  N₇ = 32 = 13+19 ✓ (質數對)")
print()
print("  5=2+3, 12=5+7, 18=7+11, 32=13+19 — 質數對和!")
print("  N₅ = 25 = 11+14? 唔係... 25 = 2+23 ✓ 但 23 質數")
print()
# 質數對 (差 2,4,6...)
pairs_18 = [(7, 11)]
pairs_32 = [(13, 19)]
pairs_25 = [(2, 23), (12, 13)]
print("  25 = 2+23 (質數對, 差 21)? 或者 12+13 (12 非質數)")
print("  更自然: 25 = 5+7+13? = 25 ✓ (連續質數 5,7,13)")
