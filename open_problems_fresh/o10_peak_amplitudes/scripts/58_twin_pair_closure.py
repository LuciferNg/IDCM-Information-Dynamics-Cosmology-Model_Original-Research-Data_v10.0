import numpy as np, math

phi = (1 + 5**0.5) / 2
eps = phi**-1/4

A = {1: 1.0000, 2: 0.4434, 3: 0.4389, 5: 0.2143, 7: 0.1414}

print("=" * 72)
print("質數孿生對閉合")
print("=" * 72)

# P₁ = (A₂+A₃)/2
P1 = (A[2]+A[3])/2
P1_th = 3*eps
print(f"P₁ = (A₂+A₃)/2 = {P1:.4f} vs 3ε = {P1_th:.4f}")
print(f"  偏差: {(P1-P1_th)/P1_th*100:+.2f}% (ISW 影響第一峰?)")

# P₂ = (A₅+A₇)/2
P2 = (A[5]+A[7])/2
P2_th = 3*eps*phi**-2
print(f"P₂ = (A₅+A₇)/2 = {P2:.4f} vs 3εφ⁻² = {P2_th:.4f}")
print(f"  偏差: {(P2-P2_th)/P2_th*100:+.2f}% ✅")

# 對內比例
print()
print("對內比例:")
r1 = A[3]/A[2]
r2 = A[7]/A[5]
print(f"  對1 (2,3): A₃/A₂ = {r1:.4f} ≈ 1 (F₁/F₂ = 1)")
print(f"  對2 (5,7): A₇/A₅ = {r2:.4f} ≈ 2/3 (F₃/F₄ = 0.667)")

# 對內分配模型
print()
print("對內分配模型 (Fibonacci 連續比):")
print("  對1: A₂ = P₁×F₂/(F₁+F₂), A₃ = P₁×F₁/(F₁+F₂)?")
print("  對2: A₅ = P₂×F₄/(F₃+F₄), A₇ = P₂×F₃/(F₃+F₄)?")
F = [1, 1, 2, 3, 5, 8, 13]

# 對1: 1:1
A2_pred = P1*F[1]/(F[0]+F[1])  # F₂/(F₁+F₂) = 1/2
A3_pred = P1*F[0]/(F[0]+F[1])  # F₁/2 = 1/2
# 對2: 3:2 (用 F₄:F₃ = 3:2)
A5_pred = P2*F[3]/(F[3]+F[2])  # F₄/(F₃+F₄) = 3/5
A7_pred = P2*F[2]/(F[3]+F[2])  # F₃/5 = 2/5

print(f"  對1: A₂ pred = {A2_pred:.4f} vs {A[2]:.4f} ({(A[2]/A2_pred-1)*100:+.1f}%)")
print(f"        A₃ pred = {A3_pred:.4f} vs {A[3]:.4f} ({(A[3]/A3_pred-1)*100:+.1f}%)")
print(f"  對2: A₅ pred = {A5_pred:.4f} vs {A[5]:.4f} ({(A[5]/A5_pred-1)*100:+.1f}%)")
print(f"        A₇ pred = {A7_pred:.4f} vs {A[7]:.4f} ({(A[7]/A7_pred-1)*100:+.1f}%)")

print()
print("之前嘅「對2 (4,5)」係錯配 (真峰冇 4)")
print("正確: 對2 = 質數對 (5,7)!")
print()

# 下一個質數對預測
print("=" * 72)
