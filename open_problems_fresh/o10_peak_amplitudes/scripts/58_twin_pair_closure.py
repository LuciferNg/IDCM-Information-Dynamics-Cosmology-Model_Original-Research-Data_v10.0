print(f"  P₁ (2,3)   = 3ε = {3*eps:.4f}")
print(f"  P₂ (5,7)   = 3εφ⁻² = {3*eps*phi**-2:.4f}")
print(f"  P₃ (11,13) = 3εφ⁻⁴ = {3*eps*phi**-4:.4f}")
print(f"  P₄ (17,19) = 3εφ⁻⁶ = {3*eps*phi**-6:.4f}")
print()
print("質數對 m 用 φ^(-2(m-1)) 階梯, F_m 重數喺邊?")
print()
print("之前: P_m = 3ε·F_m·φ^(-2(m-1))  (F = 1,1,2,3)")
print("而家: P_m = 3ε·φ^(-2(m-1))  (冇 F_m?)")
print()
print("檢查: P₃ (11,13) 嘅預測?")
print("  如果 P₃ = 3ε·F₃·φ⁻⁴ = 2×0.0676 = 0.1353")
