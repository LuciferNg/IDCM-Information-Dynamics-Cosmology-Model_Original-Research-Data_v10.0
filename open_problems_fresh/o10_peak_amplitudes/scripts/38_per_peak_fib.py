#!/usr/bin/env python3
"""
O10 38: 每峰獨立 Fibonacci 分配 — 完整結構
===========================================
假設: 每對嘅兩個峰共享 F_m 重數, 但按 F_{2m-1}:F_{2m} 比例分配?

峰 2,3 (P₁, F₁=1): 比例 1:1 → 峰2 = 1/2, 峰3 = 1/2 of P₁?
峰 4,5 (P₂, F₂=1): 比例 2:3 → 峰4 = 2/5, 峰5 = 3/5 of P₂?

但 F₂ = 1 (唔係 2+3=5)...
或者: 每峰獨立重數?
  峰2 = F₂ = 1
  峰3 = F₃ = 2?
  峰4 = F₄ = 3?
  峰5 = F₅ = 5?

檢查: 峰4:峰5 = F₄:F₅ = 3:5 = 0.6? 但實際 0.66 (2/3)
"""
import numpy as np, math

phi = (1 + 5**0.5) / 2
eps = phi**-1/4
F = [1, 1, 2, 3, 5, 8, 13, 21, 34]

# Planck 真峰
A = {1: 1.0000, 2: 0.4434, 3: 0.4389, 4: 0.2143, 5: 0.1414}

print("=" * 72)
print("每峰獨立 Fibonacci 假設")
print("=" * 72)

# 假設 1: 每峰重數 = F_m (峰 m 用 F_m)
print("\n假設 1: 峰 m 重數 = F_m, 峰高 ∝ F_m·φ^(-a_m)?")
# 峰 2,3: F₂=1, F₃=2 → 比 1:2? 但實際 1:0.99 ❌

# 假設 2: 峰 m 重數 = F_{m-1}?
print("\n假設 2: 峰 m 重數 = F_{m-1}:")
for m in [2, 3, 4, 5]:
    print(f"  峰{m}: F_{m-1} = {F[m-2]}")

# 假設 3: 簡併對 (2m-1, 2m) 嘅重數 = (F_{2m-2}, F_{2m-1})?
print("\n假設 3: 對 m 內: 峰 2m-1 = F_{2m-2}, 峰 2m = F_{2m-1}")
for m in [1, 2]:
    a, b = 2*m-1, 2*m
    Fa, Fb = F[a-1], F[b-1]
    print(f"  對{m}: 峰{a} = F_{a-1} = {Fa}, 峰{b} = F_{b-1} = {Fb}, 比 = {Fa/Fb:.4f}")
    print(f"        vs 實際: {A[b]/A[a]:.4f}")

print()
print("對1: F₁/F₂ = 1/1 = 1 vs 實際 0.99 ✅")
print("對2: F₃/F₄ = 2/3 = 0.667 vs 實際 0.66 ✅ (1% 偏差)")
print()
print("→ 峰 2m-1 重數 = F_{2m-2}, 峰 2m 重數 = F_{2m-1}")
print("→ 即: 峰 2,3 = (F₂, F₃)? 錯! 用 F_{2m-2}, F_{2m-1}:")
print("  對1: 峰2 = F₂ = 1, 峰3 = F₃ = 2? 唔啱 (比要 1:1)")
print()
print("更正: 峰 2m-1 重數 = F_{2m-3}?")
for m in [1, 2]:
    a, b = 2*m-1, 2*m
    # 峰 a (odd), 峰 b (even)
    print(f"  對{m}: 峰{a} (odd) vs 峰{b} (even)")

# 直接檢查: 峰 2,3 比 = F_1:F_2? = 1:1 ✅
#           峰 4,5 比 = F_3:F_4? = 2:3 ✅
# 即: 峰 m 重數 = F_{m-1} (峰2=F₁=1, 峰3=F₂=1, 峰4=F₃=2, 峰5=F₄=3)?
print()
print("直接檢查: 峰 m 重數 = F_{m-1}:")
for m in [2, 3, 4, 5]:
    print(f"  峰{m}: F_{m-1} = {F[m-2]}")
print("  峰2=F₁=1, 峰3=F₂=1 → 比 1:1 ✅")
print("  峰4=F₃=2, 峰5=F₄=3 → 比 2:3 ✅")
print()
print("🎯 峰 m 重數 = F_{m-1}!")

# 完整公式: 峰 m 高度 = ?
# 峰 1 = 1 (基準)
# 峰 m = 3ε·F_{m-1}·φ^{-2(?)}?
# 峰 2,3 (m=2,3): 平均 = 3ε → 每峰 = 3ε/2? (F₁=F₂=1 平分)
# 峰 4,5 (m=4,5): 平均 = 3εφ⁻² → 峰4 = 2/5, 峰5 = 3/5
print()
print("每峰高度公式:")
print("  峰 2m-1 = P_m × F_{2m-2}/(F_{2m-2}+F_{2m-1})")
print("  峰 2m   = P_m × F_{2m-1}/(F_{2m-2}+F_{2m-1})")
print("  P_m = 3ε·F_m·φ^(-2(m-1))")

# 驗證
print()
print("驗證:")
for m in [1, 2]:
    a, b = 2*m-1, 2*m
    Fa, Fb = F[a-1], F[b-1]  # F_{2m-2}, F_{2m-1}
    P_m = 3*eps*F[m-1]*phi**(-2*(m-1))
    Aa_pred = P_m * Fa/(Fa+Fb)
    Ab_pred = P_m * Fb/(Fa+Fb)
    print(f"  對{m}: 峰{a} pred={Aa_pred:.4f} (obs {A[a]:.4f}), 峰{b} pred={Ab_pred:.4f} (obs {A[b]:.4f})")
    print(f"    比 = {Fa/Fb:.4f} vs obs {A[b]/A[a]:.4f}")
