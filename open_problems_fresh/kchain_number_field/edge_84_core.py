print("  世界 = 84 + 6 (γ_44 + γ_88)")
print("  邊集 = 84 + γ_1 (種子)")
print(f"  世界 − 邊集 = 6 − γ_1 = {6-g1:.6f}")
print(f"  6 = γ_44 + γ_88 = 2+4")

print("\n" + "="*72)
