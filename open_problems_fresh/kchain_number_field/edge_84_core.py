print(f"γ_88 = {g88:.6f} (冇對偶, Nyquist)")
print(f"γ_87 = {g87:.6f} (γ_1 對偶)")
print(f"γ_1  = {g1:.6f} (種子)")
print()
print(f"觀察者 88 = 22 對 × 4                = 22×4")
print(f"世界 90   = 21 對 × 4 + γ_44 + γ_88  = 84 + 2 + 4")
