print("="*72)
# 世界 (偶數) 21 對: k=2,4,...,42 ↔ 86,84,...,46
world_pairs = [(k, 88-k) for k in range(2, 44, 2)]
print(f"世界 21 對: {world_pairs[0]} .. {world_pairs[-1]}  (共 {len(world_pairs)} 對)")
# 邊集 (奇數) 21 對: m=85,83,...,3 ↔ 3,5,...,85 (但 m=1 孤單)
edge_pairs = [(m, 88-m) for m in range(3, 86, 2) if m < 88-m]
print(f"邊集 21 對: {edge_pairs[0]} .. {edge_pairs[-1]}  (共 {len(edge_pairs)} 對)")

print("\n" + "="*72)
print("2. 對偶點嘅數值")
print("="*72)
# 世界對: (2,86), (4,84), ..., (42,46)
wp_sum = sum(4*sin(a*pi/176)**2 + 4*sin(b*pi/176)**2 for a,b in world_pairs)
print(f"世界 21 對 Σγ = {wp_sum:.6f} (應為 21×4=84)")
# 邊集對: (3,85), (5,83), ..., (43,45)
ep_sum = sum(4*sin(a*pi/176)**2 + 4*sin(b*pi/176)**2 for a,b in edge_pairs)
print(f"邊集 21 對 Σγ = {ep_sum:.6f} (應為 21×4=84)")
print(f"兩者相等? {abs(wp_sum - ep_sum) < 1e-10}")

print("\n" + "="*72)
