print("2. γ_n + γ_{88−n} 對偶 (88-site)")
print("="*72)
for n in [1, 11, 22, 33, 44]:
    gn = 4*sin(n*pi/176)**2
    g88n = 4*sin((88-n)*pi/176)**2
    print(f"  γ_{n:2d} + γ_{88-n:2d} = {gn:.6f} + {g88n:.6f} = {gn+g88n:.6f} {'✅ =4' if abs(gn+g88n-4)<1e-10 else ''}")

