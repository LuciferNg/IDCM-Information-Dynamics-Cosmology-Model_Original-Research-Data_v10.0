"""
K_Chain 數域結構驗證 IV — 有理骨架生成結構 + 特殊 mode 地位
=============================================================
問題:
1. 44 個 γ_n 係咪 Q-線性生成 Q(ζ_88)⁺? (用個別 mode 數值高精度 rank 測試)
2. γ_22 = 2 點解特殊? (唯一 v_g = c 嘅 mode)
3. 有理骨架 {Σ=90, γ_n+γ_{44-n}=4} 嘅代數本質
4. γ_11, γ_33 共軛對嘅封閉形式結構
5. ω_n 嘅 sin-cos 對偶: ω_n² + ω_{44-n}² = 4?
"""
import numpy as np
import math

N_d = 44
print("=" * 78)
print("K_Chain 有理骨架生成結構 — 驗證 IV")
print("=" * 78)

# ═══════════════════════════════════════════════════════════
# 1. ω_n² + ω_{44-n}² = 4? (sin-cos 對偶)
# ═══════════════════════════════════════════════════════════
print("\n1. ω_n² + ω_{44-n}² 檢查 (sin-cos 對偶)")
print("-" * 60)
w = np.array([2 * math.sin(math.pi * n / 88) for n in range(1, N_d + 1)])
ok = True
for n in range(1, N_d + 1):
    # ω_{44-n}: n=44 時係 ω_0 = 0 (boundary), n=22 自對偶 ω_22²+ω_22² = 2+2 = 4
    if n == 44:
        s = w[43]**2 + 0.0  # ω_44² + ω_0², ω_0 = 0
    else:
        s = w[n-1]**2 + w[N_d-n-1]**2
    if abs(s - 4) > 1e-12:
        ok = False
        print(f"  ❌ n={n}: {s}")
print(f"  ω_n² + ω_{{44-n}}² = 4 ∀n: {'✅' if ok else '❌'}")
print(f"  (因為 ω_n = 2sin(πn/88), ω_44-n = 2cos(πn/88) → sin²+cos² = 1 → 4)")

# ═══════════════════════════════════════════════════════════
# 2. γ_n 嘅 Q-線性生成 — 用 QR rank 測試
# ═══════════════════════════════════════════════════════════
print("\n2. γ_n 全體嘅 Q-線性生成")
print("-" * 60)
gamma = np.array([4 * math.sin(math.pi * n / 88)**2 for n in range(1, N_d + 1)])

# 用高精度數值 (mpmath) 建立 Vandermonde 型矩陣, 測試 rank
import mpmath as mp
mp.mp.dps = 50

# γ_n 嘅 Q-線性獨立測試: 用 44 個 γ 嘅一次冪矩陣 (rank = Q-span 維度)
# 但 γ_n ∈ Q(ζ_88)⁺ 係 20 維 — 所以 rank ≤ 20
# 方法: 用 mpmath LU 分解 rank
def mp_rank(M):
    """mpmath 矩陣 rank (LU 消元法)"""
    M = mp.matrix(M)
    rows, cols = M.rows, M.cols
    r = 0
    for col in range(cols):
        # 搵 pivot
        pivot = None
        for row in range(r, rows):
            if abs(M[row, col]) > mp.mpf('1e-40'):
                pivot = row
                break
        if pivot is None:
            continue
        # mpmath row swap: 用暫存變數
        tmp = mp.matrix(M)
        for c2 in range(cols):
            M[r, c2], M[pivot, c2] = M[pivot, c2], M[r, c2]
        pv = M[r, col]
        for row in range(r+1, rows):
            factor = M[row, col] / pv
            for c2 in range(col, cols):
                M[row, c2] -= factor * M[r, c2]
        r += 1
        if r == rows:
            break
    return r

# 用 44 個 γ_n 嘅 [1, γ, γ², ..., γ^19] 嵌入 — 如果 γ_n 生成 Q(ζ_88)⁺,
# 44 個數值嘅 Q-rank 應該 ≥ 20
V = mp.matrix(44, 20)
for i in range(44):
    for j in range(20):
        V[i, j] = mp.mpf(gamma[i]) ** j

r = mp_rank(V)
print(f"  γ_n 嵌入矩陣 (44×20) 嘅 rank = {r}")
print(f"  ⇒ Q(ζ_88)⁺ 次數 = 20, rank = {r} {'✅ 生成整個數域' if r >= 20 else '⚠️ 只生成子域'}")

# ═══════════════════════════════════════════════════════════
