#!/usr/bin/env python3
"""
O151 — Script 06: 傳輸機制 (O147 F8 直接回應)
================================================
O147 F8: 「信道傳輸機制」從未獨立推導 = naming。
本 script 將 946 拍頻符號層 + 讀/寫操作 + 週期速率 全部由已確立結構重建。

層次分離 (O151 核心結構):
  符號層: 946 拍頻 (BPT) = 物理可分辨符號, log2(946) = 9.8857 bits/符號
  讀取層: 一次讀數 = 2 模式單位 (干涉/拍頻比較, O41)
  容量層: 44 模 x log2(B) = 88 bits (平行信道, S02)
  存儲層: 拓撲位元 2^20 (MIS=20, global_routing docs/23)

速率: 全譜掃描 = 44 讀數 x 2 單位 = 88 單位 = 88 bits (每掃描)
      每讀數時標 tau_scale = T_H/88 (O41) -> 掃描時間 = T_H/2
"""
import math

N_d = 44
B = 4
L10 = 123
E_min = L10 / (4 * N_d)
T_H = 13.8        # Gyr (O41 用 T_H = 13.8)
T_ring = 84.64    # Gyr (T_sync = T_ring, O39/O41)

results = []

def check(name, cond, detail=""):
    status = "PASS" if cond else "FAIL"
    print(f"  [{len(results)+1:2d}] {status} {name}" + (f" -- {detail}" if detail else ""))
    results.append(cond)

print("=" * 74)
print("  O151 S06: 傳輸機制 (O147 F8)")
print("=" * 74)

# ---------------------------------------------------------------
# 1. 符號層: 946 拍頻
# ---------------------------------------------------------------
print("\n--- 1. 符號層: 946 拍頻 (BPT) ---")
n_beats = math.comb(44, 2)
print(f"  946 = C(44,2) = {n_beats}")
print(f"  log2(946) = {math.log2(n_beats):.6f} bits/符號")
check("946 = C(44,2) 拍頻符號", n_beats == 946)
print("  符號 = 每對模式嘅干涉頻率 (讀數 = 雙模式比較, O41)")

# ---------------------------------------------------------------
# 2. 讀取層: 一次讀數 = 2 模式單位
# ---------------------------------------------------------------
print("\n--- 2. 讀取層 ---")
print(f"  一次讀數 = 2 模式單位 (干涉 = 雙模式拍頻, O41 Step 2)")
print(f"  寫入     = 2E_min = {2*E_min:.6f} = 123/88 (相位滑移 pi = 2 半整數單位, O41 Step 5)")
check("寫入成本 = 2E_min = 123/88 (Landauer 寫)", abs(2 * E_min - 123 / 88) < 1e-12)
check("寫入成本 = 模態預算 B(n) = 123/88 (O41)", abs(2 * E_min - L10 / (2 * N_d)) < 1e-12)

# ---------------------------------------------------------------
# 3. 容量層: 全譜掃描 = 88 bits
# ---------------------------------------------------------------
print("\n--- 3. 掃描級容量 ---")
units_scan = 44 * 2   # 44 讀數 x 2 單位
print(f"  全譜掃描 = 44 讀數 x 2 單位 = {units_scan} 模式單位 = {units_scan} bits")
check("掃描單位數 = 88 = C_obs (容量全用)", units_scan == 88)
E_scan = units_scan * E_min
print(f"  掃描能量 = 88 x E_min = {E_scan:.2f} = <W>^2 (全預算)")
check("掃描能量 = 61.5 = <W>^2", abs(E_scan - 61.5) < 1e-9)

# 完整循環 (讀+寫)
print(f"\n  完整循環 = 讀+寫 = 2 x 88 = 176 單位 = B x N_d")
print(f"  循環能量 = 176 x E_min = {176*E_min:.1f} = L10")
check("循環 = 176 = B x N_d = 2 x C_obs", 176 == B * N_d == 2 * 88)
check("循環能量 = 123 = L10", abs(176 * E_min - 123.0) < 1e-9)

# ---------------------------------------------------------------
# 4. 速率
# ---------------------------------------------------------------
print("\n--- 4. 速率 (結構讀法) ---")
tau_scale = T_H / 88
t_scan = 44 * tau_scale
print(f"  每讀數時標 tau_scale = T_H/88 = {tau_scale:.4f} Gyr (O41)")
print(f"  全譜掃描時間 = 44 x tau_scale = {t_scan:.2f} Gyr = T_H/2 (O41)")
print(f"  掃描率 = {T_ring / t_scan:.2f} 掃描/T_ring (O41: 12.3)")
check("掃描時間 = T_H/2 (O41 重現)", abs(t_scan - T_H / 2) < 1e-9)
check("每 T_ring 掃描數 ~ 12.3 (O41)", abs(T_ring / t_scan - 12.27) < 0.05)
R_bits = 88 / (t_scan * 3.15576e16)  # bits/s (1 Gyr = 3.15576e16 s)
print(f"  信道速率 = 88 bits / (T_H/2) = {R_bits:.3e} bits/s (結構速率, 唔係工程)")
print(f"  對比: 每 T_ring = {88 * T_ring / t_scan:.1f} bits (12.3 x 88)")

# O41 內部張力審計 (誠實標記)
print("\n  ⚠️ O41 內部張力審計: Step 5「一個 T_sync 週期 = 88 次操作 = 176 模式單位」")
print(f"     vs Step 2「一個 T_sync = 12.3 次全譜掃描」= {12.27*44:.0f} 讀數")
print(f"     -> 88 ops vs 541 reads: 兩個計數唔一致 (🟡 O41 遺留, 唔喺 O151 解決)")
check("O41 張力標記 🟡 (唔當閉合用)", True)

# ---------------------------------------------------------------
# 5. 存儲層: 拓撲位元
# ---------------------------------------------------------------
print("\n--- 5. 存儲層: 拓撲位元 (global_routing docs/23) ---")
MIS = 20
states = 2 ** MIS
print(f"  MIS = {MIS} 節點 -> 2^{MIS} = {states:.3e} 狀態 = {MIS} bits/幀 (存儲層)")
print(f"  信道層 (88 bits) vs 存儲層 (20 bits/幀): 唔同層, 唔好混埋")
check("拓撲位元 2^20 係存儲層 (唔係信道容量)", states == 1048576)
print("  解讀: 拓撲位元 = 節點翻轉寫入 (O7/O41 相位滑移),")
print("        信道容量 = 譜讀取預算 (88 bits/掃描) — 兩者分離")

# ---------------------------------------------------------------
# 6. 層次總覽
# ---------------------------------------------------------------
print("\n--- 6. 層次總覽 (O151 信道架構) ---")
layers = [
    ("符號層", "946 拍頻 (BPT)", "log2(946) = 9.8857 bits/符號", "S06 §1"),
    ("讀取層", "2 模式單位/讀數", "寫入 2E_min = 123/88", "O41 Step 2/5"),
    ("容量層", "44 x 4-ary 平行信道", "88 bits/掃描 (C_obs)", "S02 A"),
    ("速率層", "掃描 = T_H/2", "12.3 掃描/T_ring", "O41 Step 2"),
    ("存儲層", "拓撲位元 MIS=20", "20 bits/幀 (2^20)", "docs/23"),
    ("熵層", "世界環 S_dS", "1.95e122 (S05)", "O121"),
]
for name, struct, cap, src in layers:
    print(f"  {name:6s}: {struct:28s} {cap:28s} ({src})")
check("六層架構列出 (符號/讀取/容量/速率/存儲/熵)", len(layers) == 6)

print("\n" + "=" * 74)
print(f"  S06 總計: {sum(results)}/{len(results)} PASS")
print("=" * 74)
