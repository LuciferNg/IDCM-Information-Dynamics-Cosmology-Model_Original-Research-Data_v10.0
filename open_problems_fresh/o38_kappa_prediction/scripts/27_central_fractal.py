from mpmath import mpf, sin, pi, mp
mp.dps = 40

print("=" * 76)
print("  O38/m0-scale — 中樞・不動點・左右分形・分形張量 (scripts/27)")
print("=" * 76)

# ═══ [A] 中央: 左右鏡像對稱 γ_{88−n} = γ_n ═══
print("\n─── [A] 中央: 左右鏡像對稱 (γ_n = 4sin²(πn/88)) ───")
gamma = {n: mpf(4)*sin(mpf(n)*pi/mpf(88))**2 for n in range(1, 89)}
ok = all(abs(gamma[n] - gamma[88-n]) < mpf("1e-30") for n in range(1, 88))
print(f"  ∀n∈[1,87]: γ_{{88−n}} = γ_n  →  {'✅ 精確 (≤1e-30)' if ok else '❌'}")
print(f"  中心 n=44: γ_44 = {float(gamma[44]):.10f} (=4, 對稱軸)")
print(f"  邊緣 n=1:  γ_1  = {float(gamma[1]):.10f} = γ_{{87}} ({float(gamma[87]):.10f})")
print(f"  ⟹ 88 鏈有明確中央 (n=44 對稱軸, 偶數鏈 → 軸喺格間)")

