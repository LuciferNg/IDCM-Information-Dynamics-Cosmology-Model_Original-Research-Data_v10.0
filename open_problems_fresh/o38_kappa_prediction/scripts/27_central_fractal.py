print(f"  Σγ(88, 1..44)    = {float(s88):.6f}  (p3 權威 90 ✓)")
print(f"  Σγ̃(176, 1..88)   = {float(s176_half):.6f}  (半譜和 = 90+88 = Σγ(88)+κ̃² ✓)")
print(f"  Σγ̃(176, 1..176)  = {float(s176_full):.6f}  (標準: Σ4sin²(πn/N)=2N = 352)")
print(f"  Σγ̃(352, 1..352)  = {float(s352):.6f}  (標準: 2N ✓)")
print(f"  ⟹ 級聯 Σ4sin²(πn/2N) = 4N; 半譜和 Σγ̃(1..88) = 178 = 90+88 = 2F₁₁ (記錄, 唔升格)")

