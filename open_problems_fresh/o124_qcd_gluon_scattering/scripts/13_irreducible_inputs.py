print("           j=0 退化: 2γ₄₄ = 4 ⟹ γ₄₄ = μ² = 2 ⟹ B = 2μ²")
print("         φ 封閉式: B = φ³ + ψ³ = φ³ − φ⁻³ = L₃ = 4")
print("         端點鎖定: α⁻¹(0) = C(B²,2) + B² + 1 = 137 ⟹ B⁴+B²−272=0 ⟹ B²=16")
print("     (2) α⁻¹ = 繞數:")
print("         端點: α⁻¹(0) = C(B²,2)+F_proj, α⁻¹(M_Z) = C(B²,2)+2B")
print("         Δα⁻¹ = F_proj − 2B = B²−2B+1 = (B−1)² = 9")
