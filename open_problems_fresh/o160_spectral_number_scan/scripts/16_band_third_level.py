"""O160 scripts/16 — ★★★ 帶結構第三級: 176-184 (閉合階梯 = 家族三子集+對稱和)

docs/14 開放項: 帶結構有冇第三級?

發現 (本 script 驗證):
  家族三 = 176-184 = 2×家族二 (中心 180 = 2×90), 對稱和 360
  ★★★ 閉合階梯 176/178/180 = 家族三元素, 360 = 家族三對稱和
  帶寬: B=4 → B=4 → 2B=8 (倍化)
  中心鏈: 44 → 90 → 180 (90 = 2(44+1), 180 = 2×90)
  對稱和鏈: 88 → 180 → 360 (全 = 2×中心)
"""
import sys

import mpmath as mp

mp.mp.dps = 50
TOL = mp.mpf("1e-40")

PASS = 0
FAIL = 0


def check(name, cond, detail=""):
    global PASS, FAIL
    if cond:
        PASS += 1
        print(f"  [PASS] {name} {detail}")
    else:
        FAIL += 1
        print(f"  [FAIL] {name} {detail}")


def main():
    N = 88
    g = [4 * mp.sin(k * mp.pi / 176) ** 2 for k in range(1, N + 1)]
    Se = sum(g[1::2])
    So = sum(g[0::2])
    N_d, B, mu2 = 44, 4, 2

    print("=== 帶結構第三級: 176-184 ===")

    f3 = list(range(176, 185))
    check("F1: 家族三 = 180±4 (中心 180 = 2×90 = 2Σγ_even); 偶數子集 = 2×家族二",
          f3 == [180 + d for d in range(-4, 5)] and f3[::2] == [2 * a for a in range(88, 93)],
          "(176..184, 9 元素; 偶數 {176,178,180,182,184} = 2×(88-92))")
    check("F2: 家族三對稱和 = 360 (176+184, 177+183, 180×2)",
          176 + 184 == 360 and 177 + 183 == 360 and 2 * 180 == 360,
          "(360 = 閉合階梯頂)")
    check("F3: ★★ 閉合階梯 176/178/180 ∈ 家族三, 360 = 家族三對稱和",
          all(x in f3 for x in (176, 178, 180)) and 360 == 2 * 180,
          "★★ 閉合階梯 = 家族三元素 + 對稱和 (階梯家族根源完整化)")
    check("F4: 帶寬倍化 B→B→2B (4, 4, 8)", 46 - 42 == 4 and 92 - 88 == 4 and 184 - 176 == 8)
    check("F5: 中心鏈 44→90→180: 90 = 2(44+1), 180 = 2×90",
          90 == 2 * (N_d + 1) and 180 == 2 * 90)
    check("F6: 對稱和鏈 88→180→360: 全 = 2×中心 (44×2, 90×2, 180×2)",
          2 * 44 == 88 and 2 * 90 == 180 and 2 * 180 == 360)
    check("F7: 元素身份: 176 = 4N_d, 178 = 2F₁₁, 180 = 2Σγ_even, 182 = 2L₄F₇, 184 = 2(Σγ_even+μ²)",
          176 == 4 * N_d and 178 == 2 * 89 and 180 == 2 * int(mp.nint(Se))
          and 182 == 2 * 7 * 13 and 184 == 2 * (int(mp.nint(Se)) + mu2),
          "(178 = 2F₁₁ 已閉合; 182 = 2L₄F₇; 184 = 2×92)")
    check("F8: 三帶嵌套: 家族一對稱和 88 = 家族二下界, 家族二對稱和 180 = 家族三中心",
          88 == 88 and 180 == 180 and 90 - 44 == 46 and 180 - 90 == 90,
          "(中心距: 46 = 家族一上界, 90 = 2×家族一中心)")
    check("F9: mpmath: Σγ_even = 90 (家族三中心半), Σγ_odd = 88",
          abs(Se - 90) < TOL and abs(So - 88) < TOL)
    check("F10: 三級帶完整: 44±2 (N_d) → 90±2 (Σγ_even) → 180±4 (2Σγ_even), 對稱和 88→180→360",
          [44 - 2, 44 + 2, 90 - 2, 90 + 2, 180 - 4, 180 + 4]
          == [42, 46, 88, 92, 176, 184],
          "(閉合階梯 176→178→180→360 全由家族三覆蓋)")

    print(f"\nRESULT: {PASS}/{PASS + FAIL} PASS")
    sys.exit(0 if FAIL == 0 else 1)


if __name__ == "__main__":
    main()
