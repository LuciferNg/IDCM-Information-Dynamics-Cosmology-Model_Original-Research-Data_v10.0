import sys

def check(name, cond, note=""):
    print(f"[{'PASS' if cond else 'FAIL'}] {name} {note}")
    return cond

results = []
B, S_odd, S_even, F11, L4, F7 = 4, 88, 90, 89, 7, 13

# ── F1-F3: 家族模式 ────────────────────────────────────────
families = {2: (88, 92, 90, 4), 3: (176, 184, 180, 8), 4: (352, 368, 360, 16), 5: (704, 736, 720, 32)}
results.append(check(
    "F1: ★★★★ 家族_n = 2^{n−2}×家族二 (範圍)",
    all(lo == 2 ** (n - 2) * 88 and hi == 2 ** (n - 2) * 92 for n, (lo, hi, c, w) in families.items()),
    "(88-92, 176-184, 352-368, 704-736)"))
results.append(check(
    "F2: ★ 中心 = 2^{n−2}×Σγ_even = 2^{n−2}×90",
    all(c == 2 ** (n - 2) * S_even for n, (lo, hi, c, w) in families.items()),
    "(90, 180, 360, 720)"))
results.append(check(
    "F3: ★ 寬度 = 2^{n−2}×B (4, 8, 16, 32)",
    all(w == 2 ** (n - 2) * B for n, (lo, hi, c, w) in families.items()),
    "(帶寬倍化: B, 2B, 4B, 8B)"))

# ── F4-F6: 家族五 5 命中 ────────────────────────────────────
results.append(check(
    "F4: ★ 家族五偶數 8-子集 = 8×家族二 = {704, 712, 720, 728, 736}",
    [8 * a for a in range(88, 93)] == [704, 712, 720, 728, 736],
    "(T21 只登記 3 個, 漏 712/728)"))
results.append(check(
    "F5: ★★ 家族五命中 5 個全有身份: 704=8×88=8圈 i⁸=1, 712=8F₁₁, 720=8×90, 728=8L₄F₇, 736=8×92",
    704 == 8 * S_odd and 712 == 8 * F11 and 720 == 8 * S_even and 728 == 8 * L4 * F7 and 736 == 8 * (S_even + 2),
    "(零新常數)"))
results.append(check(
    "F6: ★ 命中率 5/33 = 15.2% vs 密度 4% → 3.8×富集 (修正 T21 9%)",
    len([704, 712, 720, 728, 736]) == 5 and 33 == len(range(704, 737)) and 5 / 33 > 0.14,
    f"(5/33 = {5/33:.1%})"))

# ── F7-F9: 自旋 + 級聯 ─────────────────────────────────────
results.append(check(
    "F7: 704 = 8 圈 = 1440° = 720°×2 (i⁸ = 1 週期重複, T23 交叉)",
    704 == 8 * 88 and 1j ** 8 == 1 and 8 * 88 * 180 / 88 == 1440,
    "(自旋週期重複 — 冇新本徵, 物理封頂家族四)"))
