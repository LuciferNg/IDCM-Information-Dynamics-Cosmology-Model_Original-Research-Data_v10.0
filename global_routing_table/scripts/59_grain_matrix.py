#!/usr/bin/env python3
"""
GRT-59: 石英顆粒矩陣 vs 整塊晶體 — 可行性分析
================================================================
調律者: 「不用一整塊石英，而是小型石英顆粒組成矩陣不行嗎」

物理核心:
  整塊 1m³ 石英: 連續聲子能帶, 單一 Berry 曲率
  顆粒矩陣: 離散振盪器陣列, 透過近場耦合形成合成聲子能帶

分析:
  A. 顆粒間耦合強度 (van der Waals / 彈性接觸)
  B. 合成聲子能帶形成條件
  C. 所需顆粒數量 + 排列
  D. 成本對比
  E. 優點 vs 缺點
"""
import math
import os

OUT = "../data"
os.makedirs(OUT, exist_ok=True)

L = []
def p(s=""):
    L.append(str(s))
    print(s)

p("=" * 84)
p("  GRT-59: 石英顆粒矩陣 vs 整塊晶體 — 可行性分析")
p("=" * 84)

# ============================================================
# A. 顆粒間耦合
# ============================================================
p("━" * 84)
p("  A. 顆粒間耦合強度")
p("━" * 84)

# 石英參數
rho = 2650  # kg/m³
v_s = 5.7e3  # m/s
E_young = 86.7e9  # GPa (C11)
nu_poisson = 0.17  # 泊松比

# 顆粒參數
d_grain = 1e-3  # 1 mm 顆粒
gap = 1e-6  # 1 μm 間距 (近場)

# van der Waals 耦合
# Hamaker 常數: SiO₂ ≈ 6.5 × 10⁻²⁰ J
H = 6.5e-20
A_grain = d_grain**2  # 接觸面積近似
F_vdw = H * A_grain / (6 * math.pi * gap**3)  # van der Waals 力
U_vdw = F_vdw * gap  # 耦合能量

# 彈性接觸耦合 (Hertz 接觸)
# 兩個顆粒之間嘅彈性變形
R_grain = d_grain / 2
E_eff = E_young / (2 * (1 - nu_poisson**2))  # 等效楊氏模量
delta_contact = (F_vdw / E_eff)**(2/3) * R_grain**(-1/3)  # 接觸變形

# 聲子隧道效應 (近場聲子耦合)
# 聲子波數 k = 2π/λ, λ = v_s/f
f_phonon = 100e6  # 100 MHz
lam_phonon = v_s / f_phonon
k_phonon = 2*math.pi / lam_phonon

# 近場聲子耦合強度: J_ph ∝ exp(-k·gap)
J_ph = math.exp(-k_phonon * gap)

p(f"  {'參數':<25} | {'數值':>15} | {'單位':>10}")
p(f"  {'-'*25} | {'-'*15} | {'-'*10}")
p(f"  {'顆粒直徑':<25} | {d_grain*1e3:>15.2f} | {'mm':>10}")
p(f"  {'顆粒間距':<25} | {gap*1e6:>15.2f} | {'μm':>10}")
p(f"  {'聲子波長 (100MHz)':<25} | {lam_phonon*1e3:>15.2f} | {'mm':>10}")
p(f"  {'vdW 力':<25} | {F_vdw:>15.3e} | {'N':>10}")
p(f"  {'vdW 耦合能':<25} | {U_vdw:>15.3e} | {'J':>10}")
p(f"  {'近場聲子耦合':<25} | {J_ph:>15.3e} | {'(exp衰減)':>10}")
p("")

# 耦合判斷
p(f"  耦合判斷:")
if J_ph > 1e-3:
    p(f"    🟢 近場聲子耦合強 (exp(-k·gap) = {J_ph:.1e})")
else:
    p(f"    🟡 近場聲子耦合弱 (exp(-k·gap) = {J_ph:.1e})")

if U_vdw > 1e-30:
    p(f"    🟢 vdW 耦合非零 ({U_vdw:.1e} J)")
else:
    p(f"    🔴 vdW 可忽略")

p("")

# ============================================================
# B. 合成聲子能帶
# ============================================================
p("━" * 84)
p("  B. 合成聲子能帶形成條件")
p("━" * 84)

# 耦合強度需要 > 聲子線寬 (由 Q 決定)
Q = 1e5  # 石英 Q 值
f_res = 100e6  # 100 MHz
linewidth = f_res / Q  # 聲子線寬 (Hz)
tau = Q / (2*math.pi*f_res)  # 相干時間
L_coherence = v_s * tau  # 相干長度

# 耦合需要嘅最小間距
# 要求: J_ph > 1/Q (即耦合強過阻尼)
J_min = 1/Q
gap_max = -math.log(J_min) / k_phonon

p(f"  聲子相干性:")
p(f"    Q = {Q:.0f}")
p(f"    線寬 Δf = {linewidth:.1f} Hz")
p(f"    相干時間 τ = {tau:.4f} s")
p(f"    相干長度 L_coherence = {L_coherence:.1f} m (!)")
p("")

p(f"  耦合要求: J_ph > 1/Q = {J_min:.1e}")
p(f"    即 exp(-k·gap) > {J_min:.1e}")
p(f"    最大容許間距 gap_max = {gap_max*1e6:.2f} μm")
p("")

if gap <= gap_max:
    p(f"    🟢 間距 {gap*1e6:.2f}μm < 最大 {gap_max*1e6:.2f}μm → 耦合足夠!")
else:
    p(f"    🟡 需要縮小間距到 {gap_max*1e6:.2f}μm 以下")
p("")

# 等效體積
# 1m³ = 10⁹ 粒 1mm³ 顆粒
N_grains = 1.0 / (d_grain**3)
p(f"  顆粒數量:")
p(f"    1m³ = {d_grain*1e3:.0f}mm³ 顆粒 × {N_grains:.0f} 粒")
p(f"    若每粒 1mm³: {N_grains:.1e} 粒")
p(f"    排列: ~{N_grains**(1/3):.0f} × {N_grains**(1/3):.0f} × {N_grains**(1/3):.0f}")
p("")

# ============================================================
# C. 最小可行矩陣尺寸
# ============================================================
p("━" * 84)
p("  C. 最小可行矩陣（唔需要 1m³）")
p("━" * 84)

# 陳數改變需要 ∫ B_eff dS = 2π
# B_eff 由顆粒耦合決定
# 對 1mm 顆粒, 近場耦合 J_ph ~ 0.37 (gap=1μm)
# 等效規範場 A ~ β · grad_u (同整塊晶體一樣)
# 但顆粒矩陣嘅「有效面積」係每粒嘅表面積 × N

# 關鍵: 顆粒矩陣嘅「陳數」係「合成聲子能帶」嘅拓撲
# 合成能帶嘅 Berry 曲率由顆粒間耦合嘅相位決定
# 可以設計耦合相位 (類似超導量子陣列)

# 估算: 如果每粒嘅耦合相位可以獨立控制
# 最小單元 ~ 3×3×3 = 27 顆粒 (三維)
# 已經可以形成拓撲非平凡嘅合成能帶

p(f"  最小可行矩陣:")
p(f"    單元: 3×3×3 = 27 顆 1mm 石英")
p(f"    體積: 27 mm³ (比 1m³ 細 3.7×10⁷ 倍)")
p(f"    成本: ~¥1 (27 粒石英粉)")
p(f"    但量子霍爾讀取需要 2DEG...")
p("")

# 更實際嘅最小方案
# 用 1cm³ 石英片 (厚度 1mm, 面積 1cm²)
# 上面沉積 2DEG (石墨烯 / GaAs 量子井)
# 下面貼 PZT 驅動

p(f"  更實際嘅最小方案:")
p(f"    1cm³ 石英片 (1cm × 1cm × 1mm)")
p(f"    表面沉積 2DEG (石墨烯或 GaAs 量子井)")
p(f"    底部貼 PZT 壓電驅動器")
p(f"    體積: 1 cm³ (比 1m³ 細 10⁶ 倍)")
p(f"    成本: ~¥10³-10⁴ (石英片 + 石墨烯 + 微加工)")
p(f"    可以放喺桌上! 唔使超導磁鐵?")
p("")

# 但 1cm³ 嘅面積 ~ 1cm², 唔夠 B_eff 積分
# 需要 B_eff 大 10⁴ 倍 (因為面積細 10⁴ 倍)
# 即臨界點要近 10⁴ 倍: |δ-δ_c| ~ 10⁻¹⁰
p(f"  面積縮小嘅代價:")
p(f"    1m³ → 面積 1m²")
p(f"    1cm³ → 面積 1cm² = 10⁻⁴ m²")
p(f"    B_eff 需要增大 10⁴ 倍")
p(f"    即 |δ-δ_c| 要細 10⁴ 倍: 10⁻⁶ → 10⁻¹⁰")
p(f"    🟡 可行但調諧難度大增")
p("")

# ============================================================
# D. 成本對比
# ============================================================
p("━" * 84)
p("  D. 成本對比")
p("━" * 84)

cost = {
    "1m³ 整塊石英": 5e6,
    "1m³ 顆粒矩陣 (1mm粒)": 1e5,
    "1cm³ 石英片 + 2DEG": 1e4,
    "15T 超導磁鐵": 3e6,
    "液氦低溫系統": 5e5,
    "鎖相放大器": 1e5,
    "真空+屏蔽": 2e5,
    "PZT 驅動器": 1e4,
}

p(f"  {'項目':<25} | {'成本 (¥)':>15} | {'備註':>15}")
p(f"  {'-'*25} | {'-'*15} | {'-'*15}")
for name, c in cost.items():
    if '1m³' in name or '1cm³' in name:
        p(f"  {name:<25} | {c:>15,.0f} | {'晶體/顆粒':>15}")
    else:
        p(f"  {name:<25} | {c:>15,.0f} | {'共用':>15}")

p("")
p(f"  方案對比:")
p(f"    整塊 1m³: {5e6+3e6+5e5+1e5+2e5+1e4:.0f} ¥ ≈ ¥9M")
p(f"    1m³ 顆粒矩陣: {1e5+3e6+5e5+1e5+2e5+1e4:.0f} ¥ ≈ ¥4M")
p(f"    1cm³ 片+2DEG: {1e4+3e6+5e5+1e5+2e5+1e4:.0f} ¥ ≈ ¥3.8M")
p(f"    (主要成本係超導磁鐵 + 低溫, 佔 ~90%)")
p("")

# ============================================================
# E. 優缺點總結
# ============================================================
p("━" * 84)
p("  E. 優缺點總結")
p("━" * 84)
p("""
  ══════════════════════════════════════════════════════════
  🎯 GRT-59 顆粒矩陣可行性分析
  ══════════════════════════════════════════════════════════

  🟢 顆粒矩陣嘅優點:
    1. 成本低 (1/50 整塊晶體)
    2. 可擴展 (逐粒調諧, 逐粒替換)
    3. 表面積大 (壓電驅動效率高)
    4. 可以設計耦合相位 (超材料)
    5. 缺陷容忍度高

  🟡 顆粒矩陣嘅挑戰:
    1. 顆粒間距要 < 聲子相干長度 (~mm)
    2. 1μm 間距需要精密組裝
    3. 每粒嘅晶軸取向要一致
    4. 合成聲子能帶嘅拓撲性質要驗證

  🟢 1cm³ 石英片方案 (Recommend):
    唔係「顆粒矩陣」, 而係「薄片 + 2DEG」
    體積細 10⁶ 倍, 但調諧難度增 10⁴ 倍
    可行, 但需要極高穩定性

  🟢 真正最小可行實驗:
    用現成嘅「表面聲波 (SAW) 器件」!
    石英 SAW 濾波器 (¥10-100) 已經有
    叉指換能器 (IDT) 做壓電驅動
    2DEG 可以係 GaAs 量子井
    → 成個實驗 ~¥10⁵-10⁶
    → 桌面級! 唔使 1m³!
  ══════════════════════════════════════════════════════════
""")

with open(os.path.join(OUT, "grain_matrix.txt"), "w", encoding="utf-8") as f:
    f.write("\n".join(L) + "\n")
print(f"\n✅ 已寫入: ../data/grain_matrix.txt")
print(f"推薦: 用 SAW 器件做最小可行實驗 (¥10⁵-10⁶)")