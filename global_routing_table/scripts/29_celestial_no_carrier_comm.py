# 二、BFS 路由 + hop 矩陣
# ============================================================
def bfs_all_pairs(adj, N):
    hop = np.full((N, N), -1, dtype=np.int16)
    for s in range(N):
        hop[s, s] = 0
        q = deque([s])
        while q:
            u = q.popleft()
            for v in adj[u]:
                if hop[s, v] == -1:
                    hop[s, v] = hop[s, u] + 1
                    q.append(v)
    return hop

hop = bfs_all_pairs(adj, N)
