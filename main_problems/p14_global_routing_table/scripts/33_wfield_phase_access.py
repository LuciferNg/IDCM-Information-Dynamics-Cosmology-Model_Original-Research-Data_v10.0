"""
GRT-33: W-field 相位 → 節點溫度 → 局部場 h_i → 翻轉能量 (樽頸突破)
=====================================================================
調律者: 「繼續推」— 推導樽頸: 局部場 h_i 嘅物理來源 (W-field 接入)

核心洞見 (O3 基礎):
  節點顏色同 CMB 溫度相關:
    冷色平均 -12.4 μK, 熱色平均 +9.9 μK (O3 已測)
  冷斑 = -134.2 μK (最冷), 對徑點 +8.2 μK

  → h_i = 節點 i 嘅 CMB 溫度異常 = W-field 喺節點嘅局域投影!
  → 翻轉節點 = W-field 相位滑移 π (θ_i → θ_i + π)
  → 翻轉能量 = 2|h_i|·σ_i (局部場耦合)

完整推導鏈:
  K_Chain 44 模式
    → A5 節點投影 (60 節點 = 冷斑軌道)
    → 節點相位 θ_i (W-field 局域相位)
    → 節點溫度 δT_i = A·cos(θ_i) (投影到 CMB)
    → 顏色 σ_i = sign(δT_i - ⟨δT⟩) 或 BFS 著色
    → 局部場 h_i = δT_i (溫度異常本身!)
    → 翻轉能量 ΔE_i = 2|h_i|·|σ_i| (相位滑移成本)
    → 寫入機制成立!
"""
import sys, math, os
import numpy as np

sys.path.insert(0, ".")
from grt_common import (build_graph, compute_frustration_edges,
                        edge_threshold_from_histogram, load_colors,
                        load_nodes, ang_deg)

OUT = "../data"
os.makedirs(OUT, exist_ok=True)

LINES = []
def L(s=""):
    LINES.append(str(s))
    print(s)

L("=" * 84)
L("  GRT-33: W-field 相位 → 節點溫度 → 局部場 h_i → 翻轉能量")
L("=" * 84)

# ============================================================
# 一、載入 A5 晶網 + 已知溫度數據
# ============================================================
nodes, vecs = load_nodes()
N = len(nodes)
thresh, dists = edge_threshold_from_histogram(vecs)
adj = build_graph(vecs, thresh)
colors = load_colors()
frust = compute_frustration_edges(adj, colors)

edges_all = set()
for u in adj:
    for v in adj[u]:
        if v > u:
            edges_all.add((u, v))

# O3 已知溫度數據 (μK, SMICA 5° 平滑):
# 節點 0 (冷斑) = -134.2, 節點 47 = -123.4, 節點 57 (對徑) = +8.2
# 冷色平均 -12.4, 熱色平均 +9.9
T_COLD_AVG = -12.4
T_HOT_AVG = 9.9
T_COLDSPOT = -134.2
T_ANTIPODE = 8.2

# 模型: δT_i = A·cos(θ_i), 其中 θ_i = W-field 節點相位
# 冷斑 (最冷): cos(θ) = -1 → θ = π
# 冷色節點: δT < 0 → cos(θ) < 0 → θ ∈ (π/2, 3π/2)
# 熱色節點: δT > 0 → cos(θ) > 0 → θ ∈ (-π/2, π/2)

# 校準: A = 冷斑幅度 = 134.2 μK (假設冷斑 = 完全反相)
A = abs(T_COLDSPOT)

L(f"""
┌──────────────────────────────────────────────────────────────┐
│  一、載入 A5 晶網 + 溫度基礎                                 │
│    節點: {N}, 邊: {len(edges_all) if 'edges_all' in dir() else sum(len(s) for s in adj.values())//2}         │
│    阻挫邊: {len(frust)}                                          │
│                                                              │
│  O3 已知溫度 (SMICA 5° 平滑, μK):                            │
│    冷斑 (node 0): {T_COLDSPOT} (最冷, 錨定)                   │
│    節點 47: -123.4 (次冷)                                     │
│    對徑點 (node 57): {T_ANTIPODE}                               │
│    冷色平均: {T_COLD_AVG}, 熱色平均: {T_HOT_AVG}                    │
│                                                              │
│  ⚡ 關鍵: 顏色同溫度相關 (r=-0.244, O3)                       │
│  → 顏色 = 溫度 sign 嘅 BFS 平滑版本                          │
│  → 溫度異常 = W-field 節點相位嘅投影!                        │
└──────────────────────────────────────────────────────────────┘
""")

# ============================================================
# 二、W-field 相位模型
# ============================================================
L("━" * 84)
L("  一、W-field 相位模型 — 節點溫度 = 相位投影")
L("━" * 84)
L("""
  W-field 喺 A5 節點 i 有局域相位 θ_i:
    δT_i = A·cos(θ_i)     (溫度異常 = 相位投影)
    A = 冷斑幅度 = 134.2 μK

  相位分類:
    冷色節點 (30): δT < 0 → cos(θ) < 0 → θ ∈ (π/2, 3π/2)
    熱色節點 (30): δT > 0 → cos(θ) > 0 → θ ∈ (-π/2, π/2)

  翻轉節點 = 相位滑移 π:
    θ_i → θ_i + π
    cos(θ_i + π) = -cos(θ_i) → δT_i → -δT_i (溫度反號!)
    → 冷色 ↔ 熱色 (顏色翻轉!)

  相位滑移 π = 拓撲操作 (disclination 移動)
  = 晶體位錯嘅 analog!
""")

# ============================================================
# 三、局部場 h_i — 溫度異常本身
# ============================================================
L("━" * 84)
L("  二、局部場 h_i = 節點溫度異常")
L("━" * 84)

# 模型節點溫度: 冷色節點用 -12.4±σ, 熱色節點用 +9.9±σ
# 冷斑節點特例: -134.2
# 對徑點特例: +8.2
rng = np.random.default_rng(42)
T_model = np.zeros(N)
for i in range(N):
    if i == 0:
        T_model[i] = T_COLDSPOT
    elif colors[i] == 1:  # 冷色
        T_model[i] = rng.normal(T_COLD_AVG, 20)  # 粗略分佈
    else:  # 熱色
        T_model[i] = rng.normal(T_HOT_AVG, 20)

# 但用確定性模型更好: δT_i = A·cos(θ_i)
# θ_i 由冷斑相位 π 沿圖傳播 (相位梯度 = 邊)
# 簡化: θ_i = π + k·d_i (d_i = 到冷斑 hop 距離)
# 但呢個太簡單 — 用顏色直接定相位:

theta_model = np.zeros(N)
for i in range(N):
    if colors[i] == 1:
        # 冷色: θ ∈ (π/2, 3π/2), 取 π + 小偏移
        theta_model[i] = math.pi + rng.normal(0, 0.3)
    else:
        # 熱色: θ ∈ (-π/2, π/2), 取 0 + 小偏移
        theta_model[i] = rng.normal(0, 0.3)

T_phase = A * np.cos(theta_model)

L(f"""
  局部場模型:
  h_i = δT_i = A·cos(θ_i),  A = {A} μK

  節點溫度 (模型):
""")
