# 5 節點圖 (環)
adj5 = {0: [1, 4], 1: [0, 2], 2: [1, 3], 3: [2, 4], 4: [3, 0]}

def sg5(theta, omega, dt, inj_node=None, inj_strength=0, inj_duration=0, t=0):
    dtheta = omega.copy()
    domega = np.zeros(N5)
    for i in range(N5):
        domega[i] = -gamma5 * omega[i] - (E_J5 + h5[i]) * math.sin(theta[i])
        for j in adj5[i]:
            domega[i] -= J5 * math.sin(theta[i] - theta[j] - alpha5_f(i,j))
        if inj_node is not None and i == inj_node and t < inj_duration:
            domega[i] += inj_strength
    return dtheta, domega

def sg5_integrate(theta0, omega0, dt, steps, inj_node=None, inj_strength=0, inj_duration=0):
    theta = theta0.copy()
    omega = omega0.copy()
    t = 0.0
    for step in range(steps):
        k1t, k1o = sg5(theta, omega, dt, inj_node, inj_strength, inj_duration, t)
        k2t, k2o = sg5(theta + 0.5*dt*k1t, omega + 0.5*dt*k1o, dt, inj_node, inj_strength, inj_duration, t+0.5*dt)
        k3t, k3o = sg5(theta + 0.5*dt*k2t, omega + 0.5*dt*k2o, dt, inj_node, inj_strength, inj_duration, t+0.5*dt)
        k4t, k4o = sg5(theta + dt*k3t, omega + dt*k3o, dt, inj_node, inj_strength, inj_duration, t+dt)
        theta = theta + (dt/6)*(k1t + 2*k2t + 2*k3t + k4t)
        omega = omega + (dt/6)*(k1o + 2*k2o + 2*k3o + k4o)
        t += dt
    return theta, omega

