"""
GRT-36: 相位滑移觸發物理 — W-field 激發耦合到節點相位
================================================================
調律者: 「B」— 推導相位滑移 π 嘅觸發物理 (能量注入如何耦合)

核心問題: 點樣物理上令 θ_i → θ_i + π (翻轉節點顏色)?

推導鏈:
  K_Chain 44 模式 (宇宙晶格振動)
    → 每個模式有頻率 ω_n = 2·sin(πn/88) (色散)
    → 模式振幅 a_n (激發態)
    → A5 節點 i 嘅 W-field 相位 θ_i = Σ_n c_{i,n}·a_n (投影)
    → 相位滑移 π = 特定模式組合嘅共振激發

  關鍵: 邊個模式組合可以令 θ_i 滑移 π?
  → 需要 Σ_n c_{i,n}·Δa_n = π
  → 最簡單: 單一模式共振 Δa_n = π/c_{i,n}
  → 或: 兩個模式拍頻 (beat) 累積相位

  耦合係數 c_{i,n}: A5 節點 i 對 K_Chain mode n 嘅投影
  → 由節點位置 (RA, Dec) 決定 (幾何投影)
  → 節點 i 喺天球方向 v_i, K_Chain mode n 有空間圖案
  → c_{i,n} = 球諧/平面波投影

  觸發能量: ΔE = (1/2)·κ·(Δa_n)² (模式振幅改變嘅能量)
  → 對應 2|h_i| = 2A|cos(θ_i)| (GRT-33 翻轉能量)

  完整閉合: 能量注入 → 模式激發 → 相位滑移 π → 翻轉
"""
import sys, math, os
import numpy as np

sys.path.insert(0, ".")
from grt_common import (build_graph, compute_frustration_edges,
                        edge_threshold_from_histogram, load_colors,
                        load_nodes, ang_deg)

OUT = "../data"
os.makedirs(OUT, exist_ok=True)

LINES = []
def L(s=""):
    LINES.append(str(s))
    print(s)

L("=" * 84)
L("  GRT-36: 相位滑移觸發物理 — W-field 激發耦合到節點相位")
L("=" * 84)

# ============================================================
# 一、載入 A5 晶網 + K_Chain 參數
# ============================================================
nodes, vecs = load_nodes()
N = len(nodes)
thresh, dists = edge_threshold_from_histogram(vecs)
adj = build_graph(vecs, thresh)
colors = load_colors()
frust = compute_frustration_edges(adj, colors)

# K_Chain 參數 (source: kchain_wave_params.py)
NK = 44
R_H = 4129.94  # Mpc
C = 299792.458  # km/s
DX = R_H / NK  # 6.70 Mpc

# K_Chain 色散
omega_n = [2*math.sin(math.pi*n/88) for n in range(1, NK+1)]  # 歸一化角頻率
gamma_n = [4*math.sin(math.pi*n/88)**2 for n in range(1, NK+1)]  # eigenvalue

L(f"""
┌──────────────────────────────────────────────────────────────┐
│  A5 晶網: {N} 節點, 阻挫邊 {len(frust)}                             │
│  K_Chain: {NK} modes, 色散 ω_n = 2sin(πn/88)                     │
│  每 hop 距離 = {DX:.2f} Mpc                                        │
│                                                              │
│  觸發物理目標: θ_i → θ_i + π (翻轉節點 i)                    │
└──────────────────────────────────────────────────────────────┘
""")

# ============================================================
# 二、耦合係數 — 節點對 K_Chain mode 嘅投影
# ============================================================
L("━" * 84)
L("  一、耦合係數 c_{i,n} — 節點對 K_Chain mode 嘅投影")
L("━" * 84)
L("""
  物理圖像:
  K_Chain = 44-site 環 (宇宙晶格振動)
  A5 節點 i = 天球上嘅位置 (冷斑軌道)

  耦合: 節點 i 對 mode n 嘅響應 = 幾何投影
  c_{i,n} = |ψ_n(v_i)|²  (mode n 喺方向 v_i 嘅振幅)

  簡化模型 (K_Chain 環投影到天球):
  mode n 沿環有 k_n = n·(2π/R_H) 嘅波數
  投影到天球: 環 = 大圓 (冷斑軌道)
  節點 v_i 喺大圓嘅位置 → 相位 φ_i
  c_{i,n} = cos²(n·φ_i/2 + δ_n)  (駐波投影, n=44 係 Nyquist)

  但 A5 節點唔全部喺同一大圓!
  更實際: 用節點嘅球面座標 (θ_i, φ_i) 直接投影
  c_{i,n} = |Y_{n,m}(θ_i, φ_i)|²  (球諧投影, m=n 簡化)
""")

# 計算耦合: 用球諧 (實球諧, m 固定 = n 嘅子集)
# 簡化: c_{i,n} = cos²(Δ_i · n/44 · π/2)
# 其中 Δ_i = 節點 i 到冷斑嘅角距離 (歸一化)

cs_node = 0
# 節點到冷斑角距離 (度)
ang_to_cs = np.array([ang_deg(vecs[i], vecs[cs_node]) for i in range(N)])

# 耦合模型: c_{i,n} = cos²(n·π·ang_i/180)  (ang_i = 到冷斑角度)
# 冷斑 (ang=0): c = cos²(0) = 1 (全耦合!)
# 對徑點 (ang=180): c = cos²(nπ) = 1 (n 偶) / 0 (n 奇)
C_ij = np.zeros((N, NK))
for i in range(N):
    for n in range(NK):
        ang_rad = math.radians(ang_to_cs[i])
        C_ij[i, n] = math.cos(n * math.pi * ang_rad / 180.0) ** 2

L(f"  耦合係數 c_{{i,n}} = cos²(n·π·ang_i/180):")
L(f"  {'節點':>4} | {'到冷斑':>7} | " + " | ".join([f"n={n}" for n in [1, 11, 22, 33, 44]]) + " | 說明")
L(f"  {'-'*4} | {'-'*7} | " + " | ".join(["-----" for _ in [1,11,22,33,44]]) + " | ----")
for i in [0, 10, 22, 30, 40, 57]:
    vals = [C_ij[i, n-1] for n in [1, 11, 22, 33, 44]]
    note = "冷斑 (全耦合)" if i == 0 else ("對徑點" if i == 57 else "")
    L(f"  {i:>4} | {ang_to_cs[i]:>6.1f}° | " + " | ".join([f"{v:.3f}" for v in vals]) + f" | {note}")

