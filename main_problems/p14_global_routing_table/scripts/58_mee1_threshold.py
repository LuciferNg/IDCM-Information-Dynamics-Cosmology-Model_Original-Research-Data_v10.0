p(f"    V_needed ≈ {V_needed_linear:.1e} V — 天文級! ❌")
p("")

# 引入臨界發散
# 離臨界點 δ-δ_c, 放大因子 Λ_crit = 1/|δ-δ_c|^ν
# 需要 Λ_crit = B_boost

p(f"  引入臨界發散 (ν=1.0):")
p(f"    需要放大 = {B_boost:.1e}")
p(f"    需要 |δ-δ_c| = 1/B_boost = {1/B_boost:.1e}")
p("")

