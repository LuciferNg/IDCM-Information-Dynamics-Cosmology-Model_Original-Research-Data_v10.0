# 如果晶體尺度 1m, 需要 B_eff 增大
# B_eff_target = 2π / (1m)² = 6.28 m⁻²
B_target = 2*math.pi / 1.0  # 對 1m² 面積
B_boost = B_target / B_eff  # 需要放大倍數

p(f"  對 1m³ 晶體 (面積 1m²):")
p(f"    需要 B_eff ≈ {B_target:.2f} m⁻²")
p(f"    需要放大 {B_boost:.1e} 倍")
p("")

# 放大可以來自:
# 1. 臨界點靠近 (δ→δ_c): 臨界發散
# 2. 增大驅動功率 (應變增大)
# 3. 優化拍頻 (應變梯度增大)

