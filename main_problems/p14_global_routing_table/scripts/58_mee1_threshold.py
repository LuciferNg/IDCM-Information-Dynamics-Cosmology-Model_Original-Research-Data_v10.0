p(f"  {'參數':<20} | {'數值':>15} | {'單位':>10}")
p(f"  {'-'*20} | {'-'*15} | {'-'*10}")
p(f"  {'C11':<20} | {C['C11']:>15.2f} | {'GPa':>10}")
p(f"  {'C44':<20} | {C['C44']:>15.2f} | {'GPa':>10}")
p(f"  {'C111 (三階)':<20} | {C3['C111']:>15.0f} | {'GPa':>10}")
p(f"  {'d11 (壓電)':<20} | {d11:>15.2e} | {'C/N':>10}")
p(f"  {'密度':<20} | {rho:>15.0f} | {'kg/m³':>10}")
p(f"  {'聲速':<20} | {v_s:>15.1f} | {'m/s':>10}")
p("")

# ============================================================
# B. 應變梯度計算
# ============================================================
p("━" * 84)
p("  B. 拍頻應變梯度")
p("━" * 84)

# 驅動參數 (Gemini 建議: 100.000 MHz + 100.005 MHz → 5 kHz 拍頻)
f1 = 100e6  # Hz
f2 = 100.005e6
f_beat = abs(f1 - f2)  # 5 kHz
f_bar = (f1 + f2) / 2  # 100.0025 MHz

# 波長
lam_beat = v_s / f_beat  # 5 kHz 拍頻波長
lam_bar = v_s / f_bar   # 100 MHz 載波波長

p(f"  驅動參數:")
p(f"    f1 = {f1/1e6:.3f} MHz, f2 = {f2/1e6:.3f} MHz")
p(f"    拍頻 Δf = {f_beat/1e3:.1f} kHz")
p(f"    載波頻率 = {f_bar/1e6:.3f} MHz")
p(f"    拍頻波長 λ_beat = {lam_beat:.2f} m")
p(f"    載波波長 λ_bar = {lam_bar*1e3:.2f} mm")
p("")

# 壓電驅動產生應變
# 壓電方程: S = d·E (S = 應變, d = 壓電係數, E = 電場)
# 對 1 cm³ PZT 驅動器, 電壓 V 產生電場 E = V/t
# 應變振幅 u_amp = d11 · E

# 設 PZT 厚度 1 mm, 驅動電壓 100 V
t_pzt = 1e-3  # m
V_pzt = 100  # V
E_pzt = V_pzt / t_pzt  # V/m
strain_amp = d11 * E_pzt  # 應變振幅 (無量綱)

p(f"  壓電驅動器 (PZT, 1mm 厚, 100V 驅動):")
p(f"    電場 E = {E_pzt:.1e} V/m")
p(f"    應變振幅 S = {strain_amp:.2e} (無量綱)")
p("")

# 非線性應變梯度
# 三階彈性常數產生「應變整流」: 應變梯度 ∝ C3/C · (∂u/∂x)²
# 更精確: 拍頻包絡嘅空間梯度
# u_beat(x) = 2A·cos(Δω·t/2 - Δk·x/2) · cos(ω̄·t - k̄·x)
# 包絡: A_env(x) = 2A·cos(Δk·x/2)
# 應變梯度: ∂u/∂x ≈ u_amp · Δk/2

# 聲子振幅 u_amp (from strain: S = ∂u/∂x 嘅典型值)
# 用應變 S ~ 10⁻⁷ (100V 驅動), 波數 k = 2π/λ
k_beat = 2*math.pi / lam_beat
grad_u = strain_amp * k_beat / 2  # 包絡梯度

p(f"  非線性應變梯度:")
p(f"    拍頻波數 k_beat = {k_beat:.3f} m⁻¹")
p(f"    應變梯度 ∂u/∂x ≈ {grad_u:.3e} m⁻¹")
p("")

# 等效規範場 A_i = β · ε_ijk · ∂_j u_k
# β 係數 (由形變勢 + 晶格常數決定)
hbar = 1.054e-34
e = 1.602e-19
a_q = 5.0e-10  # 石英晶格常數 (m)
D = 8.0 * e  # 形變勢 (J)
beta = D * a_q / (hbar * v_s)  # 無量綱

p(f"  β 係數 (應變→規範場):")
p(f"    β = {beta:.2f} (無量綱)")
p("")

# 等效規範勢 A
A = beta * grad_u  # m⁻¹ (等效規範勢)
B_eff = A / lam_beat * 2*math.pi  # 等效磁場 (m⁻²)

p(f"  等效規範場:")
p(f"    A_i = {A:.3e} m⁻¹")
p(f"    B_eff = ∇×A ≈ {B_eff:.3e} m⁻²")
p("")

# ============================================================
# C. 所需功率
# ============================================================
p("━" * 84)
p("  C. 陳數改變所需功率 (ΔC = 1)")
p("━" * 84)

# 陳數 C = (1/2π) ∫ Ω d²k = (1/2π) ∫ B_eff dS
# 需要 ∫ B_eff dS = 2π 先改變 C 由 1
# 所需面積: S_needed = 2π / B_eff

S_needed = 2*math.pi / B_eff
p(f"  陳數改變條件: ∫ B_eff dS = 2π")
p(f"    目前 B_eff = {B_eff:.3e} m⁻²")
p(f"    所需面積 = {S_needed:.1f} m²")
